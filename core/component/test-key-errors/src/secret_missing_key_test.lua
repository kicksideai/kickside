local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local time = require("time")
local json = require("json")
local reader = require("reader")
local component = require("component")
local context_ops = require("context_ops")

return {run = test.run_cases(function()
    test.describe("component secret paths without an installation key", function()
        test.it("keeps non-secret reads available and refuses secret reads and writes", function()
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            db = assert(db)
            local id = uuid.v7()
            local now = time.now():utc():format_rfc3339()
            local raw, encode_err = json.encode({api_key = "missing-key-sentinel", cursor = 3})
            test.is_nil(encode_err)
            local _, insert_err = db:execute([[INSERT INTO kickside_components
                (component_id,impl_id,private_context,created_at,updated_at)
                VALUES ($1,'app:secret_kind',$2,$3,$3)]], {id, raw, now})
            test.is_nil(insert_err)
            local visible, read_err = reader.new():with_components(id)
                :include_options({private_context = true, meta = false}):one()
            test.is_nil(read_err)
            test.eq(visible.private_context.cursor, 3)
            test.eq(visible.private_context.api_key, "missing-key-sentinel")
            local private, private_err = component.get_private_context(id)
            test.is_nil(private)
            test.eq(private_err:details().code, "component_secrets_key")
            local tx, begin_err = db:begin()
            test.is_nil(begin_err)
            local changed, write_err = context_ops.set_context(tx, {component_id = id, private_context = {api_key = "replacement"}})
            local _, rollback_err = tx:rollback()
            test.is_nil(rollback_err)
            test.is_nil(changed)
            test.eq(write_err:details().code, "component_secrets_key")
            local after, after_err = db:query("SELECT private_context,context_revision FROM kickside_components WHERE component_id=$1", {id})
            test.is_nil(after_err)
            test.eq(json.decode(after[1].private_context).api_key, "missing-key-sentinel")
            test.eq(tonumber(after[1].context_revision), 0)
            local _, remove_err = db:execute("DELETE FROM kickside_components WHERE component_id=$1", {id})
            test.is_nil(remove_err)
            local _, release_err = db:release()
            test.is_nil(release_err)
        end)
    end)
end)}
