local test = require("test")
local funcs = require("funcs")
local uuid = require("uuid")
local sql = require("sql")
local context_ops = require("context_ops")
local cipher = require("cipher")
local document = require("document")
local PREFIX = document.PREFIX
local INCARNATION = "11111111-1111-4111-8111-111111111111"
local function wrong_envelope(id: string, plaintext: string): string
    local header = assert(document.header({{path = {"api_key"}, type = "string"}}, 0, INCARNATION))
    return PREFIX .. header .. ":" .. assert(cipher.seal(plaintext, string.rep("b", 32), PREFIX .. id .. ":" .. header))
end

return {run = test.run_cases(function()
    test.describe("component secret envelope failures", function()
        test.it("records exact secret paths for masked readers without declaration access", function()
            local id = uuid.v7()
            local declarations = {{path = {"auth", "password"}, type = "string"},
                {path = {"api_key"}, type = "string"}}
            local sealed, err = funcs.call("kickside.component.system:seal_secrets", id,
                {auth = {password = "path-envelope-sentinel"}}, declarations, 0, INCARNATION)
            test.is_nil(err)
            local paths, path_err = document.paths(sealed, 0, INCARNATION)
            test.is_nil(path_err)
            test.eq(paths[1].path[1], "auth")
            test.eq(paths[1].path[2], "password")
            test.eq(paths[2].path[1], "api_key")
            test.is_nil(sealed:find("path-envelope-sentinel", 1, true))
            local opened, open_err = funcs.call("kickside.component.system:open_secrets", id, sealed, 0, INCARNATION)
            test.is_nil(open_err)
            test.eq(opened.auth.password, "path-envelope-sentinel")
        end)
        test.it("authenticates the stored path header", function()
            local id = uuid.v7()
            local sealed = assert(funcs.call("kickside.component.system:seal_secrets", id,
                {api_key = "header-sentinel"}, {{path = {"api_key"}, type = "string"}}, 0, INCARNATION))
            local _, _, body, inspect_err = document.inspect(sealed, 0, INCARNATION)
            test.is_nil(inspect_err)
            local replaced = assert(document.header({{path = {"password"}, type = "string"}}, 0, INCARNATION))
            local value, err = funcs.call("kickside.component.system:open_secrets", id, PREFIX .. replaced .. ":" .. body, 0, INCARNATION)
            test.is_nil(value)
            test.eq(err:details().code, "component_secrets_cannot_decrypt")
        end)
        test.it("authenticates the incarnation even when its public header is rewritten", function()
            local id, replacement = uuid.v7(), uuid.v4()
            local declarations = {{path = {"api_key"}, type = "string"}}
            local sealed = assert(funcs.call("kickside.component.system:seal_secrets", id,
                {api_key = "incarnation-header-sentinel"}, declarations, 1, INCARNATION))
            local value, mismatch = funcs.call("kickside.component.system:open_secrets", id, sealed, 1, replacement)
            test.is_nil(value)
            test.eq(mismatch:details().code, "component_secrets_integrity")
            local _, _, body, inspect_err = document.inspect(sealed, 1, INCARNATION)
            test.is_nil(inspect_err)
            local rewritten = PREFIX .. assert(document.header(declarations, 1, replacement)) .. ":" .. body
            local forged, forged_err = funcs.call("kickside.component.system:open_secrets", id, rewritten, 1, replacement)
            test.is_nil(forged)
            test.eq(forged_err:details().code, "component_secrets_cannot_decrypt")
        end)
        test.it("reads a nullable non-secret context through the trusted boundary", function()
            local db = assert(sql.get("app:db"))
            local id = uuid.v7()
            test.is_nil(select(2, db:execute([[INSERT INTO kickside_components
                (component_id,impl_id,private_context) VALUES ($1,'app:plain_kind',NULL)]], {id})))
            local context, err = funcs.call("kickside.component.system:read_private_context", {component_id = id})
            test.is_nil(err)
            test.eq(context.component_id, id)
            test.is_nil(select(2, db:execute("DELETE FROM kickside_components WHERE component_id=$1", {id})))
            test.is_nil(select(2, db:release()))
        end)
        test.it("returns typed errors for malformed trusted read requests", function()
            local value, private_err = funcs.call("kickside.component.system:read_private_context", false)
            test.is_nil(value)
            test.is_true(errors.is(private_err, errors.INVALID))
            local response, runtime_err = funcs.call("kickside.component.system:read_runtime_context", false)
            test.is_nil(runtime_err)
            test.is_false(response.success)
            test.eq(response.kind, errors.INVALID)
        end)
        test.it("rejects an empty, unrecognized or truncated encrypted document", function()
            local id = uuid.v7()
            for _, raw in ipairs({"", "unknown:v2:AAAA", PREFIX .. "AAAA"}) do
                local value, err = funcs.call("kickside.component.system:open_secrets", id, raw, 0, INCARNATION)
                test.is_nil(value)
                test.not_nil(err)
            end
        end)
        test.it("refuses replacement writes when the existing document uses another key", function()
            local db = assert(sql.get("app:db"))
            local id = uuid.v7()
            local wrong = wrong_envelope(id, '{"api_key":"old-secret"}')
            test.is_nil(select(2, db:execute([[INSERT INTO kickside_components
                (component_id,impl_id,private_context,encrypted_secrets,context_revision,secrets_incarnation)
                VALUES ($1,'app:secret_kind','{"api_key":{"set":true}}',$2,7,$3)]], {id, wrong, INCARNATION})))
            local tx = assert(db:begin())
            local value, err = context_ops.set_context(tx, {component_id = id, private_context = {api_key = "replacement"}})
            test.is_nil(select(2, tx:rollback()))
            test.is_nil(value)
            test.eq(err:details().code, "component_secrets_cannot_decrypt")
            local rows, read_err = db:query("SELECT encrypted_secrets,context_revision FROM kickside_components WHERE component_id=$1", {id})
            test.is_nil(read_err)
            test.eq(rows[1].encrypted_secrets, wrong)
            test.eq(tonumber(rows[1].context_revision), 7)
            test.is_nil(select(2, db:execute("DELETE FROM kickside_components WHERE component_id=$1", {id})))
            test.is_nil(select(2, db:release()))
        end)
        test.it("rejects wrong keys and ciphertext substituted from another component", function()
            local id = uuid.v7()
            local bad = wrong_envelope(id, '{"api_key":"sentinel"}')
            local invalid, wrong_err = funcs.call("kickside.component.system:open_secrets", id, bad, 0, INCARNATION)
            test.is_nil(invalid)
            test.eq(wrong_err:details().code, "component_secrets_cannot_decrypt")
            local sealed, encode_err = funcs.call("kickside.component.system:seal_secrets", id, {api_key = "sentinel"}, {{path = {"api_key"}, type = "string"}}, 0, INCARNATION)
            test.is_nil(encode_err)
            local moved, moved_err = funcs.call("kickside.component.system:open_secrets", uuid.v7(), sealed, 0, INCARNATION)
            test.is_nil(moved)
            test.eq(moved_err:details().code, "component_secrets_cannot_decrypt")
        end)
    end)
end)}
