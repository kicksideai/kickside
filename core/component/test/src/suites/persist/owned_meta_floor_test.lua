local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local time = require("time")
local ops = require("ops")
local KEY = "test.owner.retry_at_ms"

return { run = test.run_cases(function()
    test.describe("owner metadata floor", function()
        local db, id
        test.before_each(function()
            local err
            db, err = sql.get("app:db")
            test.is_nil(err)
            db = assert(db)
            id = uuid.v7()
            local now = time.now():utc():format_rfc3339()
            local _, insert_err = db:execute("INSERT INTO kickside_components (component_id,impl_id,private_context,position,created_at,updated_at) VALUES ($1,$2,$3,$4,$5,$5)",
                {id, "kickside.test:meta", "{}", "n", now})
            test.is_nil(insert_err)
        end)
        test.after_each(function()
            local _, meta_err = db:execute("DELETE FROM kickside_component_meta WHERE component_id=$1", {id})
            test.is_nil(meta_err)
            local _, component_err = db:execute("DELETE FROM kickside_components WHERE component_id=$1", {id})
            test.is_nil(component_err)
            test.is_nil(select(2, db:release()))
        end)
        local function raise(value)
            test.eq(type((ops :: any).raise_meta_floor), "function")
            local tx, begin_err = db:begin()
            test.is_nil(begin_err)
            local floor, err = (ops :: any).raise_meta_floor(tx, id, KEY, value)
            if err then test.is_nil(select(2, tx:rollback())) else test.is_nil(select(2, tx:commit())) end
            return floor, err
        end
        local function row()
            local rows, err = db:query("SELECT meta_id,value,created_at FROM kickside_component_meta WHERE component_id=$1 AND key=$2", {id, KEY})
            test.is_nil(err)
            return rows[1]
        end
        test.it("protects declared owner fields from public writes and deletes while ordinary fields remain writable", function()
            for _, deletion in ipairs({false, true}) do
                local tx, begin_err = db:begin()
                test.is_nil(begin_err)
                local _, _, err = ops.set_public_meta(tx, id, deletion and {} or {[KEY] = 0}, deletion and {KEY} or nil)
                test.is_nil(select(2, tx:rollback()))
                test.not_nil(err)
                test.eq(err:kind(), errors.INVALID)
                test.eq(err:retryable(), false)
                test.eq(err:details().code, "component_meta_owner_required")
            end
            local tx, begin_err = db:begin()
            test.is_nil(begin_err)
            local _, changed, write_err = ops.set_public_meta(tx, id, {label = "visible"}, nil)
            test.is_nil(select(2, tx:commit()))
            test.is_nil(write_err)
            test.is_true(changed)
        end)
        test.it("raises monotonically across transactions while retaining row identity and creation time", function()
            local first, err = raise(20)
            test.is_nil(err)
            test.eq(first, 20)
            local original = row()
            local second, second_err = raise(10)
            test.is_nil(second_err)
            test.eq(second, 20)
            local third, third_err = raise(25)
            test.is_nil(third_err)
            test.eq(third, 25)
            local current = row()
            test.eq(current.meta_id, original.meta_id)
            test.eq(current.created_at, original.created_at)
            test.eq(current.value, "25")
        end)
        test.it("serializes competing owner updates without lowering the committed floor", function()
            test.eq(type((ops :: any).raise_meta_floor), "function")
            local tx, begin_err = db:begin()
            test.is_nil(begin_err)
            local first, first_err = (ops :: any).raise_meta_floor(tx, id, KEY, 30)
            test.is_nil(first_err)
            test.eq(first, 30)
            local started, done = channel.new(1), channel.new(1)
            coroutine.spawn(function()
                local other, open_err = sql.get("app:db")
                if open_err then started:send(true); done:send({err = open_err}); return end
                started:send(true)
                local other_tx, other_begin_err = other:begin()
                if other_begin_err then other:release(); done:send({err = other_begin_err}); return end
                local floor, err = (ops :: any).raise_meta_floor(other_tx, id, KEY, 20)
                if err then
                    local _, rollback_err = other_tx:rollback()
                    err = rollback_err or err
                else
                    local _, commit_err = other_tx:commit()
                    err = commit_err
                end
                local _, release_err = other:release()
                done:send({floor = floor, err = release_err or err})
            end)
            local began = started:receive()
            test.is_true(began)
            test.is_nil(select(2, tx:commit()))
            local result = done:receive()
            test.is_nil(result.err)
            test.eq(result.floor, 30)
            test.eq(row().value, "30")
        end)
        test.it("rejects invalid floors without changing committed metadata", function()
            test.is_nil(select(2, raise(20)))
            for _, value in ipairs({-1, 1.5, math.huge, "30"}) do
                local result, err = raise(value)
                test.is_nil(result)
                test.eq(err:kind(), errors.INVALID)
                test.eq(err:retryable(), false)
                test.eq(err:details().code, "component_meta_floor_invalid")
                test.eq(row().value, "20")
            end
        end)
        test.it("reports corrupt durable floor data without replacing it", function()
            test.is_nil(select(2, raise(20)))
            test.is_nil(select(2, db:execute("UPDATE kickside_component_meta SET value='invalid' WHERE component_id=$1 AND key=$2", {id, KEY})))
            local result, err = raise(30)
            test.is_nil(result)
            test.eq(err:kind(), errors.INTERNAL)
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "component_meta_floor_corrupt")
            test.eq(row().value, "invalid")
        end)
    end)
end) }
