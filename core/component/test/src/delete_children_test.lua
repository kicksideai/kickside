local test = require("test")
local subject = require("subject")
local fixture = require("fixture")
return {run = test.run_cases(function()
    test.describe("bounded placement dependent deletion", function()
        test.it("does not disclose invisible blockers in message or details", function()
            fixture.reset({denied = "child-1"})
            local ok, err = subject.run("parent")
            test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(err:message(), "a component under this knowledge base cannot be deleted by you; 0 child components removed")
            test.is_nil(err:details().component_id); test.eq(err:details().deleted_count, 0)
            test.eq(#fixture.deleted, 0)
        end)
        test.it("identifies visible access blockers without mutation", function()
            fixture.reset({denied = "child-1", visible = true})
            local _, err = subject.run("parent")
            test.is_true(err:message():find("child-1", 1, true) ~= nil)
            test.eq(err:details().component_id, "child-1"); test.eq(#fixture.deleted, 0)
        end)
        test.it("handles a depth of 1000 children iteratively and children-first", function()
            fixture.reset({depth = 1000})
            local ok, err = subject.run("parent")
            test.is_nil(err, tostring(err)); test.is_true(ok); test.eq(#fixture.deleted, 1000)
            test.eq(fixture.deleted[1], "child-1000"); test.eq(fixture.deleted[1000], "child-1")
        end)
        for _, tree in ipairs({{depth = 1001}, {width = 1001}}) do
            test.it("rejects a tree above 1000 descendants before any mutation: " .. (tree.depth and "deep" or "wide"), function()
                fixture.reset(tree)
                local ok, err = subject.run("parent")
                test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
                test.is_true(err:message():find("delete in parts", 1, true) ~= nil)
                test.eq(err:details().deleted_count, 0); test.eq(#fixture.deleted, 0)
            end)
        end
        test.it("starts the deadline before traversal and checks before the next read", function()
            fixture.reset({width = 2, expire_read = 1})
            local ok, err = subject.run("parent")
            test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(fixture.reads, 1); test.eq(#fixture.deleted, 0)
        end)
        test.it("checks the deadline before the next delete", function()
            fixture.reset({width = 2, expire_after_removed = true})
            local ok, err = subject.run("parent")
            test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(#fixture.deleted, 1); test.eq(err:details().deleted_count, 1)
        end)
        test.it("observes pending and running retries despite historical errors", function()
            fixture.reset({active = true})
            local ok, err = subject.run("parent")
            test.is_nil(err, tostring(err)); test.is_true(ok); test.eq(fixture.polls, 3)
        end)
        for _, status in ipairs({"dead", "cancelled"}) do
            test.it("stops on a terminal deletion job: " .. status, function()
                fixture.reset({active = true, terminal = status})
                local ok, err = subject.run("parent")
                test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
                test.eq(fixture.polls, 1); test.eq(err:details().deleted_count, 0)
                test.eq(err:details().component_id, "child-1")
            end)
        end
        test.it("checks the deadline before reading the deletion job", function()
            fixture.reset({active = true, expire_read = 4})
            local ok, err = subject.run("parent")
            test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(fixture.reads, 4); test.eq(fixture.polls, 0)
        end)
        test.it("reports the removed count and visible blocker after partial completion", function()
            fixture.reset({width = 2, fail = "child-1"})
            local ok, err = subject.run("parent")
            test.is_nil(ok); test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(err:details().deleted_count, 1); test.eq(err:details().component_id, "child-1")
            test.is_true(err:message():find("1 child components removed", 1, true) ~= nil)
            test.is_true(err:message():find("child-1", 1, true) ~= nil)
        end)
    end)
end)}
