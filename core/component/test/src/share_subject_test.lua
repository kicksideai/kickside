local test = require("test")
local share_subject = require("share_subject")

local function cases()
    test.describe("Canonical sharing subjects", function()
        test.it("keeps opaque actor IDs and group IDs", function()
            local id, err = share_subject.resolve("northwind-member-id", "user")
            test.is_nil(err)
            test.eq(id, "northwind-member-id")
            local group, group_err = share_subject.resolve("northwind-group", "group")
            test.is_nil(group_err)
            test.eq(group, "northwind-group")
        end)
        test.it("uses the directory's canonical actor ID for an email", function()
            local id, err = share_subject.resolve("member@northwind.example", "user")
            test.is_nil(err)
            test.eq(id, "northwind-member-id")
        end)
        test.it("returns a directory failure without retaining the email", function()
            local id, err = share_subject.resolve("failure@northwind.example", "user")
            test.is_nil(id)
            test.not_nil(err)
            test.is_true(errors.is(err, errors.UNAVAILABLE))
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "directory_dependency")
            test.eq(err:details().field, "refs")
        end)
        test.it("rejects an unresolved email returned as display information", function()
            local id, err = share_subject.resolve("unknown@northwind.example", "user")
            test.is_nil(id)
            test.not_nil(err)
        end)
        test.it("rejects a response without a user identity", function()
            local id, err = share_subject.resolve("missing@northwind.example", "user")
            test.is_nil(id)
            test.not_nil(err)
        end)
    end)
end
return { run = test.run_cases(cases) }
