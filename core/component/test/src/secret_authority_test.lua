local test = require("test")
local funcs = require("funcs")
local security = require("security")
local sql = require("sql")
local uuid = require("uuid")
local json = require("json")

local SENTINEL = "component-authority-secret-sentinel"
local function client(actor_id: string, trusted: boolean)
    local policies = {assert(security.policy("app:secret_caller_access"))}
    if trusted then policies[#policies + 1] = assert(security.policy("app:secret_own_kind")) end
    local scope = assert(security.new_scope(policies))
    local actor = assert(security.new_actor(actor_id))
    return assert(funcs.new()):with_actor(actor):with_scope(scope), scope, actor
end

return {run = test.run_cases(function()
    test.describe("component secrets authority", function()
        local id = ""
        test.before_each(function()
            id = uuid.v7()
            local db = assert(sql.get("app:db"))
            local _, seed_err = db:execute([[INSERT INTO kickside_components
                (component_id,impl_id,private_context) VALUES ($1,'app:secret_kind',$2)]],
                {id, assert(json.encode({api_key = SENTINEL, cursor = 7, _execution_identity = {version = 2}}))})
            test.is_nil(seed_err)
            local _, grant_err = db:execute([[INSERT INTO kickside_component_access
                (access_id,component_id,source_component_id,subject_id,subject_type,access_mask)
                VALUES ($1,$2,$3,'secret-owner','user',15)]], {uuid.v7(), id, id})
            test.is_nil(grant_err)
            test.is_nil(select(2, db:release()))
        end)
        test.after_each(function()
            local db = assert(sql.get("app:db"))
            test.is_nil(select(2, db:execute("DELETE FROM kickside_components WHERE component_id=$1", {id})))
            test.is_nil(select(2, db:release()))
        end)
        test.it("keeps existing system readers independent of binding registry authority", function()
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_system_caller")),
                assert(security.policy("app:secret_own_kind"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local value, err = call:call("kickside.component.system:read_private_context", {component_id = id})
            test.is_nil(err)
            test.eq(value.api_key, SENTINEL)
        end)
        test.it("reads migrated paths without metadata dispatch or key authority", function()
            local converted, conversion_err = funcs.call("kickside.component:retention", {})
            test.is_nil(conversion_err)
            test.is_true(converted.success)
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_direct_caller"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local value, err = call:call("app:secret_direct_reader", id)
            test.is_nil(err)
            test.eq(value.api_key.set, true)
            test.eq(value.cursor, 7)
            test.is_nil((assert(json.encode(value)):find(SENTINEL, 1, true)))
        end)
        test.it("keeps legacy internal library reads unchanged without metadata dispatch authority", function()
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_direct_caller"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local value, err = call:call("app:secret_direct_reader", id)
            test.is_nil(err)
            test.eq(value.api_key, SENTINEL)
            test.eq(value.cursor, 7)
        end)
        test.it("keeps runtime-owned context writes independent of declaration and key authority", function()
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_direct_caller"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            for _, migrated in ipairs({false, true}) do
                if migrated then test.is_true(assert(funcs.call("kickside.component:retention", {})).success) end
                local db = assert(sql.get("app:db"))
                local before = assert(db:query("SELECT encrypted_secrets,context_revision FROM kickside_components WHERE component_id=$1", {id}))[1]
                local result, err = call:call("app:secret_direct_writer", id)
                test.is_nil(err)
                test.is_true(result)
                local after = assert(db:query("SELECT private_context,encrypted_secrets,context_revision FROM kickside_components WHERE component_id=$1", {id}))[1]
                test.eq(after.encrypted_secrets, before.encrypted_secrets)
                test.eq(tonumber(after.context_revision), assert(tonumber(before.context_revision)) + 1)
                local context = assert(json.decode(after.private_context))
                test.eq(context._rollback.marker, "kept")
                test.eq(context._execution_identity.version, 2)
                test.is_nil(select(2, db:release()))
            end
        end)
        test.it("masks runtime reads of kinds outside the execution secret capability", function()
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_system_caller"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local value, err = call:call("kickside.component.system:read_private_context", {component_id = id})
            test.is_nil(err)
            test.eq(value.api_key.set, true)
            test.eq(value.cursor, 7)
            test.is_nil((assert(json.encode(value)):find(SENTINEL, 1, true)))
        end)
        test.it("migrates under the retention declaration authority without caller registry access", function()
            local actor = assert(security.new_actor("secret-owner"))
            local scope = assert(security.new_scope({assert(security.policy("app:secret_system_caller"))}))
            local call = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local result, err = call:call("kickside.component:retention", {})
            test.is_nil(err)
            test.is_true(result.success, assert(json.encode(result)))
            test.is_true(result.secret_migration.converted >= 1, assert(json.encode(result)))
            local db = assert(sql.get("app:db"))
            local row, row_err = db:query("SELECT private_context,encrypted_secrets FROM kickside_components WHERE component_id=$1", {id})
            test.is_nil(row_err)
            test.not_nil(row[1].encrypted_secrets)
            local found = (row[1].private_context :: string):find(SENTINEL, 1, true)
            test.is_nil(found)
            test.is_nil(select(2, db:release()))
        end)
        test.it("masks ordinary reads even when the execution can read secrets", function()
            local call = client("secret-owner", true)
            local value, err = call:call("kickside.component.binding:get_access_context_func", {
                component_id = id, include_context = true})
            test.is_nil(err)
            test.is_true(value.success, assert(json.encode(value)))
            test.eq(value.context.api_key.set, true)
            test.eq(value.secret_fields[1].path[1], "api_key")
            test.is_nil((assert(json.encode(value)):find(SENTINEL, 1, true)))
        end)
        test.it("requires both component access and the exact owning-kind capability", function()
            for _, request in ipairs({{actor = "secret-owner", trusted = false},
                {actor = "unrelated-execution", trusted = true}}) do
                local call = client(request.actor, request.trusted)
                local value, err = call:call("kickside.component.binding:get_secrets_func", {component_id = id})
                test.is_nil(err)
                test.is_false(value.success)
                test.eq(value.kind, errors.PERMISSION_DENIED)
                test.is_nil((assert(json.encode(value)):find(SENTINEL, 1, true)))
            end
        end)
        test.it("returns only declared strings to an authorized owning execution without exposing the key", function()
            local call, scope, actor = client("secret-owner", true)
            local value, err = call:call("kickside.component.binding:get_secrets_func", {component_id = id})
            test.is_nil(err)
            test.is_true(value.success, assert(json.encode(value)))
            test.eq(value.secrets.api_key, SENTINEL)
            test.is_nil(value.secrets.cursor)
            test.is_nil(value.secrets._execution_identity)
            test.neq(scope:evaluate(actor, "env.get", "app:secret_test_key"), "allow")
            test.neq(scope:evaluate(actor, "funcs.call", "kickside.component.system:open_secrets"), "allow")
        end)
    end)
end)}
