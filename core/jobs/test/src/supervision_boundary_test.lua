local test = require("test")
local funcs = require("funcs")
return { run = test.run_cases(function()
    test.describe("function execution supervising linked projection children", function()
        test.it("preserves a child refusal and restores the caller options", function()
            local result, err = funcs.new():call("app:projection_supervision_probe", { refuse = true })
            test.is_nil(err)
            test.not_nil(result)
            test.is_nil(result.output)
            test.contains(result.error, "worker refuses supervision batch")
            test.is_false(result.options.trap_links)
        end)
        test.it("preserves a successful child output and restores the caller options", function()
            local result, err = funcs.new():call("app:projection_supervision_probe", {})
            test.is_nil(err)
            test.is_nil(result.error)
            test.eq(result.output.count, 3)
            test.is_false(result.options.trap_links)
        end)
    end)
end) }
