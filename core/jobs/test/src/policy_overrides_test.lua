local test = require("test")
local registry = require("registry")
local sql = require("sql")
local config = require("config")
local jobs = require("jobs")
local funcs = require("funcs")
local security = require("security")

return { run = test.run_cases(function()
    test.describe("Jobs performance policy", function()
        test.it("layers defaults, host and admin through the runtime validator", function()
            local entry = assert(registry.get(config.POLICY))
            local host = config.copy(entry.meta)
            host.worker.count_postgres = 30
            local result, err = config.effective(host, entry.data.defaults, { ["worker.count_postgres"] = 40 })
            test.is_nil(err)
            test.eq(result.policy.worker_count_postgres, 40)
            test.eq(result.fields["worker.count_postgres"].source, "admin")
            local fallback = assert(config.effective(host, entry.data.defaults, {}))
            test.eq(fallback.fields["worker.count_postgres"].source, "host")
            test.eq(fallback.fields["worker.count_sqlite"].source, "default")
            test.eq(entry.data.defaults.worker.count_postgres, 4)
            test.eq(entry.data.defaults.proc.max_execution, "10m")
            test.eq(result.policy.proc_max_execution_ms, 600000)
            local scaled = assert(config.effective(entry.meta, entry.data.defaults,
                {["worker.count_postgres"] = 20, ["proc.max_execution"] = "60m"}))
            test.eq(scaled.policy.worker_count_postgres, 20)
            test.eq(scaled.policy.proc_max_execution_ms, 3600000)
        end)
        test.it("tracks explicit host values equal to defaults and restores Host after admin reset", function()
            local entry = assert(registry.get(config.POLICY))
            local host = {worker = {count_postgres = 4}, fairness = {shares = {live = 6}}}
            local effective = assert(config.effective(host, entry.data.defaults, {}))
            test.eq(effective.fields["worker.count_postgres"].source, "host")
            test.eq(effective.fields["worker.count_sqlite"].source, "default")
            test.eq(effective.fields["fairness.shares"].source, "host")
            test.eq(effective.policy.fairness_shares.backfill, 2, "partial host objects inherit missing defaults")
            local admin = assert(config.effective(host, entry.data.defaults, {["worker.count_postgres"] = 4}))
            test.eq(admin.fields["worker.count_postgres"].source, "admin")
            test.eq(assert(config.effective(host, entry.data.defaults, {})).fields["worker.count_postgres"].source, "host")
        end)
        test.it("keeps Host provenance across committed edits when the value stays equal", function()
            local original = assert(registry.current_version())
            local entry = assert(registry.get(config.POLICY))
            local changed = config.copy(entry.meta)
            changed.worker.count_postgres = 4
            local changes = assert(registry.snapshot()):changes()
            changes:update({id = entry.id, kind = entry.kind, meta = changed, data = entry.data})
            assert(changes:apply())
            local ok, err = pcall(function()
                local host = assert(jobs.get_policy())
                test.eq(host.fields["worker.count_postgres"].value, 4)
                test.eq(host.fields["worker.count_postgres"].source, "host")
                local admin = assert(jobs.set_policy_overrides({["worker.count_postgres"] = 4}))
                test.eq(admin.fields["worker.count_postgres"].source, "admin")
                local reset = assert(jobs.set_policy_overrides({}, {"worker.count_postgres"}))
                test.eq(reset.fields["worker.count_postgres"].source, "host")
            end)
            -- Clean up the admin row even when an assertion fails.
            local reset, reset_err = jobs.set_policy_overrides({}, {"worker.count_postgres"})
            local _, restore_err = registry.apply_version(original)
            test.is_nil(reset_err)
            test.not_nil(reset)
            test.is_nil(restore_err)
            test.is_true(ok, tostring(err))
            test.eq(assert(jobs.get_policy()).fields["worker.count_postgres"].source, "default")
        end)
        test.it("accepts the native duration grammar used by Host and Admin values", function()
            for _, value in ipairs({"+45s", ".5s", "1.s"}) do
                local result, err = config.runtime({["proc.max_execution"] = value})
                test.is_nil(err, value)
                test.is_true(result.proc_max_execution_ms >= 1)
            end
        end)
        test.it("rejects bounds, unknown keys and heartbeat outside the lease", function()
            local entry = assert(registry.get(config.POLICY))
            for _, values in ipairs({
                { ["worker.count_postgres"] = 257 }, { ["worker.count_sqlite"] = 3 },
                { ["worker.claim_batch"] = 1.5 }, { ["lease.heartbeat"] = "45s" },
                { ["lease.timeout"] = "500ms" }, { ["retention.jobs"] = "1d" },
                { ["fairness.shares"] = { live = 0, backfill = 0, maintenance = 0 } },
            }) do
                local value, err = config.effective(entry.meta, entry.data.defaults, values)
                test.is_nil(value)
                test.is_true(errors.is(err, errors.INVALID))
            end
        end)
        test.it("reports an offline pool and durable tier counts before a pool starts", function()
            local state, err = jobs.get_pool_state()
            test.is_nil(err)
            test.is_false(state.online)
            test.eq(state.total, 0)
            test.eq(state.busy, 0)
            for _, tier in ipairs({"live", "backfill", "maintenance"}) do
                test.is_true(type(state.queued[tier]) == "number")
                test.is_true(type(state.running[tier]) == "number")
            end
        end)
        test.it("reads runtime policy while the caller holds a SQL transaction", function()
            local db = assert(sql.get(config.db_id()))
            local tx = assert(db:begin())
            assert(tx:query("SELECT key FROM kickside_job_policy_override", {}))
            local policy, err = config.policy()
            assert(tx:rollback())
            db:release()
            test.is_nil(err)
            test.eq(policy.worker_count_postgres, 4)
        end)
        test.it("denies a direct member library caller before persisting", function()
            local scope = security.new_scope({assert(security.policy("app:policy_probe_member"))})
            local result, err = funcs.new():with_actor(security.new_actor("member", {})):with_scope(scope)
                :call("app:policy_write_probe", {})
            test.is_nil(err)
            test.is_nil(result.value)
            test.eq(result.kind, errors.PERMISSION_DENIED)
        end)
        for _, invalid in ipairs({
            {name = "duplicate", keys = {"worker.count_postgres", "worker.count_postgres"}},
            {name = "sparse", keys = {[1] = "worker.count_postgres", [3] = "worker.count_sqlite"}},
        }) do
            test.it("rejects " .. invalid.name .. " reset lists before advancing the revision", function()
                local before = assert(jobs.get_policy())
                local result, err = jobs.set_policy_overrides({}, invalid.keys)
                test.is_nil(result)
                test.is_true(errors.is(err, errors.INVALID))
                test.eq(assert(jobs.get_policy()).revision, before.revision)
            end)
        end
        test.it("commits without waiting for an offline owner and rejects empty writes", function()
            local result, err = jobs.set_policy_overrides({["worker.count_postgres"] = 41})
            test.is_nil(err)
            test.is_true(result.committed)
            test.eq(result.fields["worker.count_postgres"].value, 41)
            local empty, invalid = jobs.set_policy_overrides({}, {})
            test.is_nil(empty)
            test.is_true(errors.is(invalid, errors.INVALID))
            test.eq(assert(jobs.get_policy()).revision, result.revision)
            assert(jobs.set_policy_overrides({}, {"worker.count_postgres"}))
        end)
        test.it("persists only overrides with revisions and removes them on reset", function()
            local result, err = jobs.set_policy_overrides({ ["worker.count_postgres"] = 37,
                ["lease.timeout"] = "60s", ["lease.heartbeat"] = "15s" })
            test.is_nil(err)
            test.not_nil(result)
            local effective = assert(jobs.get_policy())
            test.eq(effective.fields["worker.count_postgres"].value, 37)
            test.eq(effective.fields["worker.count_postgres"].source, "admin")
            test.eq(assert(config.policy()).worker_count_postgres, 4, "fixed runtime reads exclude editable SQL overrides")
            test.is_true(effective.revision > 0)
            local db = assert(sql.get(config.db_id()))
            local rows = assert(db:query("SELECT key FROM kickside_job_policy_override", {}))
            db:release()
            test.eq(#rows, 3)
            local invalid, invalid_err = jobs.set_policy_overrides({ ["lease.timeout"] = "10s" })
            test.is_nil(invalid)
            test.is_true(errors.is(invalid_err, errors.INVALID))
            local unchanged = assert(jobs.get_policy())
            test.eq(unchanged.fields["lease.timeout"].value, "60s")
            test.eq(unchanged.revision, effective.revision, "invalid edits do not advance the revision")
            local reset, reset_err = jobs.set_policy_overrides({}, { "worker.count_postgres", "lease.timeout", "lease.heartbeat" })
            test.is_nil(reset_err)
            test.eq(reset.fields["worker.count_postgres"].source, "default")
            test.eq(assert(config.policy()).worker_count_postgres, 4)
            local empty_db = assert(sql.get(config.db_id()))
            local remaining = assert(empty_db:query("SELECT key FROM kickside_job_policy_override", {}))
            empty_db:release()
            test.eq(#remaining, 0)
            local explicit = assert(jobs.set_policy_overrides({["worker.count_postgres"] = 4}))
            test.eq(explicit.fields["worker.count_postgres"].source, "admin", "an explicit override stays Admin even when equal to Default")
            assert(jobs.set_policy_overrides({}, {"worker.count_postgres"}))
        end)
    end)
end) }
