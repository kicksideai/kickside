local test = require("test")
local uuid = require("uuid")
local scratch = require("migration_scratch")

local PREFIX = "kickside.core.migrations:"
local function define_tests()
    test.describe("Core migration 09", function()
        test.it("preserves events through guarded up, down and re-up and cascades subject heads", function()
            scratch.reset()
            scratch.migrate(PREFIX .. "00_encoding")
            scratch.migrate(PREFIX .. "01_thread")
            local id, event_id = uuid.v7(), uuid.v7()
            scratch.exec("INSERT INTO kickside_thread(id,component_id,thread_class) VALUES($1,$2,'migration')", { id, id })
            scratch.exec("INSERT INTO kickside_event(id,thread_id,type,role,body,seq) VALUES($1,$2,'test','user','{}',1)", { event_id, id })
            scratch.migrate(PREFIX .. "09_thread_subjects")
            scratch.migrate(PREFIX .. "09_thread_subjects")
            local rows = scratch.query("SELECT subject,subject_version FROM kickside_event WHERE id=$1", { event_id })
            test.eq(#rows, 1)
            test.is_nil(rows[1].subject)
            test.is_nil(rows[1].subject_version)
            scratch.exec("INSERT INTO kickside_thread_subject(thread_id,subject,version,last_seq,updated_at) VALUES($1,'settings',2,1,'now')", { id })
            scratch.migrate(PREFIX .. "09_thread_subjects", "down")
            test.eq(#scratch.query("SELECT id FROM kickside_event WHERE id=$1", { event_id }), 1)
            scratch.migrate(PREFIX .. "09_thread_subjects")
            scratch.exec("INSERT INTO kickside_thread_subject(thread_id,subject,version,last_seq,updated_at) VALUES($1,'settings',1,1,'now')", { id })
            scratch.exec("DELETE FROM kickside_thread WHERE id=$1", { id })
            test.eq(#scratch.query("SELECT version FROM kickside_thread_subject"), 0)
            scratch.drop()
        end)
    end)
end
return test.run_cases(define_tests)
