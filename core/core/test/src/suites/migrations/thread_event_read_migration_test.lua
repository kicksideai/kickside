local test = require("test")
local uuid = require("uuid")
local scratch = require("migration_scratch")
local PREFIX = "kickside.core.migrations:"
return {run = test.run_cases(function()
    test.describe("Core migration 13", function()
        test.it("preserves a populated thread as undeclared through upgrade and re-up", function()
            scratch.reset()
            scratch.migrate(PREFIX .. "00_encoding")
            scratch.migrate(PREFIX .. "01_thread")
            local id, event_id = uuid.v7(), uuid.v7()
            scratch.exec("INSERT INTO kickside_thread(id,component_id,attrs) VALUES($1,'legacy-text-component','{}')", {id})
            scratch.exec("INSERT INTO kickside_event(id,thread_id,type,role,body,seq) VALUES($1,$2,'test','user','{}',1)", {event_id, id})
            scratch.migrate(PREFIX .. "13_thread_event_read")
            scratch.migrate(PREFIX .. "13_thread_event_read")
            local rows = scratch.query("SELECT attrs,component_id,event_read FROM kickside_thread WHERE id=$1", {id})
            test.eq(rows[1].attrs, "{}")
            test.eq(rows[1].component_id, "legacy-text-component")
            test.eq(rows[1].event_read, "")
            test.eq(#scratch.query("SELECT id FROM kickside_event WHERE thread_id=$1", {id}), 1)
            scratch.migrate(PREFIX .. "13_thread_event_read", "down")
            scratch.migrate(PREFIX .. "13_thread_event_read")
            test.eq(scratch.query("SELECT event_read FROM kickside_thread WHERE id=$1", {id})[1].event_read, "")
            local fresh = uuid.v7()
            scratch.exec("INSERT INTO kickside_thread(id,component_id) VALUES($1,'')", {fresh})
            test.eq(scratch.query("SELECT event_read FROM kickside_thread WHERE id=$1", {fresh})[1].event_read, "")
            scratch.drop()
        end)
    end)
end)}
