local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local security = require("security")
local contract = require("contract")
local registry = require("registry")
local time = require("time")
local provision = require("provision")
local autoinit = require("autoinit")
local sweeper = require("sweeper")
local repo = require("retention_repo")

return test.run_cases(function()
    test.describe("Inherited thread retention", function()
        test.it("creates and provisions without freezing the resolved window", function()
            local owner_id = "retention-" .. uuid.v7()
            local owner = security.new_actor(owner_id,{})
            local scope = assert(security.named_scope("wippy.security:process"))
            local threads = assert(contract.get("kickside.core:threads")):with_actor(owner):with_scope(scope):open()
            local created, create_err = threads:upsert({impl_id="kickside.core.retention.pin_tests:inherited_retention_decl",thread_class="test.inherited"})
            test.is_nil(create_err)
            local id = created.thread.id
            local ids, provision_err = provision.ensure_user(owner,scope,owner_id)
            test.is_nil(provision_err)
            local provisioned = autoinit.component_id(owner_id,"test_inherited")
            local db = assert(sql.get("app:db"))
            for _,thread_id in ipairs({id,provisioned}) do
                local rows, err = db:query("SELECT event_hot_retention_days FROM kickside_retention_policy WHERE thread_id=$1",{thread_id})
                test.is_nil(err)
                test.eq(#rows,0)
            end
            local inherited, inherited_err = repo.upsert(db,id,{archive_mode="hard_delete"})
            test.is_nil(inherited_err)
            test.eq(inherited.event_hot_retention_days,30)
            local stored = assert(db:query("SELECT event_hot_retention_days FROM kickside_retention_policy WHERE thread_id=$1",{id}))
            test.is_nil(stored[1].event_hot_retention_days)
            local chosen, chosen_err = repo.upsert(db,provisioned,{event_hot_retention_days=90})
            test.is_nil(chosen_err)
            test.eq(chosen.event_hot_retention_days,90)
            local again, again_err = provision.ensure_user(owner,scope,owner_id)
            test.is_nil(again_err)
            test.eq(assert(repo.find_by_thread(db,provisioned)).event_hot_retention_days,90)
            local at = time.now():add(-60*24*time.HOUR):utc()
            local stamp = tostring(db:type())==sql.type.POSTGRES and at:format(time.RFC3339) or at:format("2006-01-02 15:04:05.000000")
            for _,thread_id in ipairs({id,provisioned}) do
                test.is_nil(select(2,db:execute([[INSERT INTO kickside_event(id,thread_id,type,role,body,seq,created_at)
                    VALUES($1,$2,'test','user','{}',1,$3)]],{uuid.v7(),thread_id,stamp})))
                test.is_nil(select(2,db:execute("UPDATE kickside_thread SET event_count=1 WHERE id=$1",{thread_id})))
            end
            local version = assert(registry.current_version())
            local ok, failure = pcall(function()
                local entry = assert(registry.get("kickside.core:policy"))
                entry.meta.retention.events="90d"
                local changes = assert(registry.snapshot()):changes()
                changes:update(entry)
                test.is_nil(select(2,changes:apply()))
                test.eq(assert(repo.find_by_thread(db,id)).event_hot_retention_days,90)
                test.eq(assert(sweeper.run_for_thread(db,id)).events,0)
                test.is_nil(select(2,registry.apply_version(version)))
                test.eq(assert(sweeper.run(db)).events,1)
                test.eq(assert(sweeper.run_for_thread(db,provisioned)).events,0)
            end)
            test.is_nil(select(2,registry.apply_version(version)))
            db:release()
            if not ok then error(failure) end
        end)
    end)
end)
