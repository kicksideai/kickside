local test = require("test")
local fixture = require("fixture")
local sql = require("sql")
local uuid = require("uuid")
local teardown = require("teardown")
local notifier = require("notifier")
local component = require("component")
local funcs = require("funcs")
local json = require("json")
return { run = test.run_cases(function()
    test.describe("Thread cleanup continuation wake", function()
        test.it("publishes committed bounded cleanup to its durable owner", function()
            local f = fixture.new()
            local thread, create_err = f.as_owner("create", { thread_class = "cleanup-wake" })
            test.is_nil(create_err, tostring(create_err))
            local id = thread.thread_id or thread.id
            local db, open_err = sql.get("app:db")
            test.is_nil(open_err)
            for i = 1, 105 do
                local _, insert_err = db:execute("INSERT INTO kickside_projection (id,thread_id,kind,body,state,last_event_seq,created_at,updated_at)"
                    .. " VALUES ($1,$2,$3,'{}','valid',0,$4,$4)",
                    { uuid.v4(), id, "wake-" .. tostring(i), "2026-01-01T00:00:00Z" })
                test.is_nil(insert_err)
            end
            notifier.reset()
            local result, err = teardown.purge_thread(db, id)
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.is_true(err:details().cleanup_pending)
            local change = notifier.last()
            test.not_nil(change, "a committed pending page wakes its durable cleanup owner")
            test.eq(change.kind, "cleanup_pending")
            test.eq(change.owner_locator.kind, "component")
            test.eq(change.owner_locator.id, id)
            db:release()
            local ok, cleanup_err = component.system_delete(id)
            test.is_true(ok, cleanup_err and json.encode({kind = cleanup_err:kind(),
                retryable = cleanup_err:retryable(), details = cleanup_err:details()}) or "cleanup returns no error")
            test.is_nil(cleanup_err)
            local tick, tick_err = funcs.new():call("kickside.component:retention", {})
            test.is_nil(tick_err)
            test.is_true(tick.success, tostring(tick.error))
        end)
    end)
end) }
