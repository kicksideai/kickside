local test = require("test")
local fixture = require("fixture")
local resource = require("resource")
local provision = require("provision")
local security = require("security")

return { run = test.run_cases(function()
    test.describe("thread provisioning conflicts", function()
        test.it("returns typed denial for an unreadable existing thread", function()
            fixture.reset(true)
            local result, err = resource.upsert({ thread_id = "thread-id" })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.PERMISSION_DENIED))
            test.eq(fixture.removed, 0)
        end)
        test.it("preserves an unreadable concurrent winner without deleting its component", function()
            fixture.reset(false)
            local result, err = resource.upsert({ thread_id = "thread-id" })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.PERMISSION_DENIED))
            test.eq(fixture.removed, 0)
        end)
        test.it("preserves a retryable provisioning conflict across materialization", function()
            local scope, scope_err = security.named_scope("wippy.security:process")
            test.is_nil(scope_err)
            local actor = security.new_actor("race-owner", {})
            local result, err = provision.ensure_user(actor, scope, "race-owner")
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.is_true((err :: any):retryable())
        end)
    end)
end) }
