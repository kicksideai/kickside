local test = require("test")
local notifier = require("notifier")
local fixture = require("fixture")
local uuid = require("uuid")
return {run = test.run_cases(function()
    test.describe("native thread audience database dependencies", function()
        for _, stage in ipairs({"get", "query"}) do
            for _, kind in ipairs({errors.NOT_FOUND, errors.ALREADY_EXISTS, errors.INVALID,
                errors.PERMISSION_DENIED, errors.UNAVAILABLE, errors.INTERNAL, errors.CANCELED,
                errors.CONFLICT, errors.TIMEOUT, errors.RATE_LIMITED, errors.UNKNOWN}) do
                for _, options in ipairs({{}, {retryable = false}, {retryable = true}}) do
                    test.it(stage .. "/" .. kind .. "/" .. tostring(options.retryable), function()
                        local source = errors.new({kind = kind, message = "audience dependency failure",
                            retryable = options.retryable, details = {code = "thread_audience_dependency", nested = {stage = stage}}})
                        fixture.reset(stage, source, false, nil)
                        local result, err = notifier.emit_thread_update({thread_id = "thread"})
                        test.is_nil(result)
                        test.eq(type(err), "userdata")
                        test.eq(err:kind(), source:kind())
                        test.eq(err:retryable(), source:retryable())
                        test.eq(err:details().code, "thread_audience_dependency")
                        test.eq(err:details().nested.stage, stage)
                        test.eq(fixture.gets, 1)
                        test.eq(fixture.queries, stage == "query" and 1 or 0)
                        test.eq(fixture.releases, stage == "query" and 1 or 0)
                        test.eq(fixture.lookups, 0)
                        test.eq(fixture.sends, 0)
                    end)
                end
            end
        end
        test.it("rejects an absent successful database response permanently", function()
            fixture.reset("", nil, true, nil)
            local result, err = notifier.emit_thread_update({thread_id = "thread"})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.INTERNAL))
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "thread_audience_database_response")
            test.eq(err:details().field, "sql.get")
            test.eq(fixture.gets, 1)
            test.eq(fixture.queries, 0)
            test.eq(fixture.releases, 0)
            test.eq(fixture.lookups, 0)
            test.eq(fixture.sends, 0)
        end)
        for _, attrs in ipairs({{user_ids = {"alice", "bob"}}, '{"user_ids":["alice","bob"]}'}) do
            test.it("retains stored table/JSON audiences/" .. type(attrs), function()
                fixture.reset("", nil, false, attrs)
                local result, err = notifier.emit_thread_update({thread_id = "thread"})
                test.is_nil(err)
                test.eq(result.recipients, 2)
                test.eq(result.topic_count, 3)
                test.eq(result.failed, 6)
                test.eq(fixture.queries, 1)
                test.eq(fixture.releases, 1)
                test.eq(fixture.lookups, 6)
                test.eq(fixture.sends, 0)
            end)
        end
        test.it("retains a real SDK SQL read with no stored audience", function()
            fixture.reset("", nil, false, nil, true)
            local result, err = notifier.emit_thread_update({thread_id = uuid.v7()})
            test.is_nil(err)
            test.eq(result.recipients, 0)
            test.eq(result.delivered, 0)
            test.eq(fixture.gets, 1)
            test.eq(fixture.queries, 1)
            test.eq(fixture.releases, 1)
            test.eq(fixture.lookups, 0)
            test.eq(fixture.sends, 0)
        end)
    end)
end)}
