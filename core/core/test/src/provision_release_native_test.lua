local test = require("test")
local provision = require("provision")
local fixture = require("fixture")
return {run = test.run_cases(function()
    test.describe("native convergence resource release", function()
        test.it("release refusal remains visible after successful convergence", function()
            local source = errors.new({kind = errors.UNAVAILABLE, message = "release refusal", retryable = false,
                details = {code = "release_refusal", nested = {marker = "kept"}}})
            fixture.reset("release", source)
            local summary, err = provision.converge({}, {})
            test.eq(summary.healed, 1)
            test.eq(type(err), "userdata")
            test.eq(err:kind(), source:kind())
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "release_refusal")
            test.eq(err:details().nested.marker, "kept")
            test.eq(fixture.releases, 1)
        end)
        test.it("release refusal retains the preceding scan failure", function()
            local source = errors.new({kind = errors.CONFLICT, message = "scan refusal", retryable = false,
                details = {code = "scan_refusal", nested = {marker = "scan"}}})
            local release = errors.new({kind = errors.UNAVAILABLE, message = "release refusal", retryable = true,
                details = {code = "release_refusal", nested = {marker = "release"}}})
            fixture.reset("thread_scan_release", source)
            fixture.release_source = release
            local summary, err = provision.converge({}, {})
            test.eq(summary.checked, 0)
            test.eq(err:kind(), release:kind())
            test.eq(err:retryable(), true)
            test.eq(err:details().code, "release_refusal")
            test.eq(err:details().operation_error.kind, source:kind())
            test.eq(err:details().operation_error.retryable, false)
            test.eq(err:details().operation_error.details.code, "scan_refusal")
            test.eq(err:details().operation_error.details.nested.marker, "scan")
            test.eq(fixture.releases, 1)
        end)
    end)
end)}
