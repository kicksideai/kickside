local test = require("test")
local cipher = require("secret_cipher")
local crypto = require("crypto")
local base64 = require("base64")

return {run = test.run_cases(function()
    test.describe("authenticated secret storage", function()
        test.it("decodes a complete AES-256 key and rejects malformed keys", function()
            local key, err = cipher.decode_key(string.rep("01aB", 16))
            test.is_nil(err)
            test.eq(key, string.rep(string.char(1, 171), 16))
            for _, hex in ipairs({"", string.rep("a", 63), string.rep("a", 66), string.rep("gg", 32), string.rep(" a", 32), string.rep("+a", 32)}) do
                local invalid, invalid_err = cipher.decode_key(hex)
                test.is_nil(invalid)
                test.is_true(errors.is(invalid_err, errors.INVALID))
            end
        end)
        test.it("reads the existing nonce-prefixed AES-GCM base64 format", function()
            local key = string.rep("a", 32)
            local raw, encrypt_err = crypto.encrypt.aes("credential", key)
            test.is_nil(encrypt_err)
            local stored, encode_err = base64.encode(raw)
            test.is_nil(encode_err)
            local plain, err = cipher.open(stored :: string, key)
            test.is_nil(err)
            test.eq(plain, "credential")
            local sealed, seal_err = cipher.seal(plain, key)
            test.is_nil(seal_err)
            local decoded, decode_err = base64.decode(sealed :: string)
            test.is_nil(decode_err)
            local compatible, decrypt_err = crypto.decrypt.aes(decoded, key)
            test.is_nil(decrypt_err)
            test.eq(compatible, plain)
        end)
        test.it("authenticates the key, ciphertext and associated component", function()
            local key = string.rep("b", 32)
            local stored, err = cipher.seal("credential", key, "component-one")
            test.is_nil(err)
            local plain, read_err = cipher.open(stored :: string, key, "component-one")
            test.is_nil(read_err)
            test.eq(plain, "credential")
            local wrong, wrong_err = cipher.open(stored :: string, string.rep("c", 32), "component-one")
            test.is_nil(wrong)
            test.not_nil(wrong_err)
            local moved, moved_err = cipher.open(stored :: string, key, "component-two")
            test.is_nil(moved)
            test.not_nil(moved_err)
            local raw, decode_err = base64.decode(stored :: string)
            test.is_nil(decode_err)
            local tampered, encode_err = base64.encode(raw:sub(1, #raw - 1)
                .. string.char((raw:byte(#raw) + 1) % 256))
            test.is_nil(encode_err)
            local changed, changed_err = cipher.open(tampered, key, "component-one")
            test.is_nil(changed)
            test.not_nil(changed_err)
            local malformed, malformed_err = cipher.open("%%invalid", key)
            test.is_nil(malformed)
            test.not_nil(malformed_err)
        end)
        test.it("uses fresh nonces for repeated writes", function()
            local key = string.rep("d", 32)
            local first, first_err = cipher.seal("credential", key)
            test.is_nil(first_err)
            local second, second_err = cipher.seal("credential", key)
            test.is_nil(second_err)
            test.eq(first == second, false)
        end)
    end)
end)}
