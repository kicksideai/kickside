local test = require('test')
local security = require('security')
local sql = require('sql')
local registry = require('registry')
local env = require('env')

return {run = test.run_cases(function()
    test.describe('environment signing across token store boot and update', function()
        test.it('RUNTIME-TOKENSTORE-BOOT-ENV-SIGNING signs at boot and preserves saved signed tokens on update', function()
            test.not_nil((registry.get('settings:signing')))
            test.is_true(type(env.get('ENCRYPTION_KEY')) == 'string', 'Signing environment is registered')
            local db = assert(sql.get('app:db'))
            local _, create_err = db:execute([[CREATE TABLE auth_tokens (
                token_key TEXT PRIMARY KEY, token_value BYTEA NOT NULL, expires_at TIMESTAMP
            )]])
            test.is_nil(create_err)
            local actor = assert(security.new_actor('member', {}))
            local scope = assert(security.new_scope({}))
            local store = assert(security.token_store('app:auth'))
            local saved, mint_err = store:create(actor, scope, {})
            store:close()
            test.is_nil(mint_err)
            test.is_true(type(saved) == 'string' and saved:find('.', 1, true) ~= nil,
                'Boot bearer has no signature')
            local before = assert(db:query('SELECT token_value FROM auth_tokens'))
            test.eq(#before, 1)
            local entry = assert(registry.get('app:auth'))
            entry.data.token_length = 48
            local changes = assert(registry.snapshot()):changes()
            changes:update(entry)
            local _, update_err = changes:apply()
            test.is_nil(update_err)
            store = assert(security.token_store('app:auth'))
            local restored, _, validate_err = store:validate(saved)
            test.is_nil(validate_err)
            test.not_nil(restored)
            local after = assert(db:query('SELECT token_value FROM auth_tokens'))
            test.eq(#after, 1)
            test.eq(after[1].token_value, before[1].token_value)
            local base = saved:match('^([^.]+)')
            local unsigned, _, unsigned_err = store:validate(base)
            test.is_nil(unsigned)
            test.not_nil(unsigned_err)
            local fresh, fresh_err = store:create(actor, scope, {})
            test.is_nil(fresh_err)
            test.is_true(type(fresh) == 'string' and fresh:find('.', 1, true) ~= nil,
                'Updated bearer has no signature')
            test.not_nil((store:validate(fresh)))
            test.is_true((store:revoke(saved)))
            test.is_true((store:revoke(fresh)))
            store:close()
            db:release()
        end)
    end)
end)}
