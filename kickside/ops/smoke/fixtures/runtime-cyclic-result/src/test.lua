local test = require('test')
local funcs = require('funcs')
return {run = test.run_cases(function()
    test.describe('cyclic native function results', function()
        test.it('UPSTREAM-FUNCS-CYCLIC-RESULT formats a failed assertion without stack overflow', function()
            local result, err = funcs.call('app:cyclic_result', {})
            test.is_nil(err)
            test.not_nil(result)
            test.is_true(result.loop == result)
            local accepted, diagnostic = pcall(test.is_nil, result)
            test.is_false(accepted)
            test.contains(tostring(diagnostic), 'assertion failed', tostring(diagnostic))
        end)
    end)
end)}
