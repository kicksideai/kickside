local test = require("test")
local fs = require("fs")
local registry = require("registry")
local branding = require("branding")
local settings_writer = require("settings_writer")
local migration_runner = require("migration_runner")

local function normal_update()
    local runner = migration_runner.setup("app:db")
    local _, err = runner:find_migrations()
    test.is_nil(err, tostring(err))
    local result = runner:run()
    test.eq(result.migrations_failed, 0, tostring(result.error))
end

local function define_tests()
    test.describe("branding stored by earlier releases", function()
        test.it("imports the configured filesystem logo before serving branding", function()
            local config, config_err = registry.get("kickside.ui:legacy_branding_config")
            test.is_nil(config_err, tostring(config_err))
            local storage, storage_err = fs.get(config.data.fs)
            test.is_nil(storage_err, tostring(storage_err))
            local bytes = "RIFF\4\0\0\0WEBP"
            local written, write_err = storage:writefile("logo.webp", bytes)
            test.is_nil(write_err, tostring(write_err))
            test.is_true(written)
            local saved, save_err = settings_writer.set("kickside.ui", "logo_url", "/kickside-branding/logo.webp", "fixture")
            test.is_nil(save_err, tostring(save_err)); test.is_true(saved)
            normal_update()
            local image = branding.read()
            test.not_nil(image, "normal migrations leave the configured filesystem image unreadable")
            test.eq(image.bytes, bytes)
            test.eq(image.content_type, "image/webp")
            local settings = assert(settings_writer.reload())
            test.eq(settings["kickside.ui\0logo_url"].value, branding.url())
            normal_update()
            test.eq(branding.read().bytes, bytes)
        end)
        test.it("preserves an existing database image while updating its legacy URL", function()
            local bytes = "saved database image"
            branding.save(bytes, "image/png")
            local saved, save_err = settings_writer.set("kickside.ui", "logo_url", "/kickside-branding/logo.png", "fixture")
            test.is_nil(save_err, tostring(save_err)); test.is_true(saved)
            normal_update()
            test.eq(branding.read().bytes, bytes)
            local settings = assert(settings_writer.reload())
            test.eq(settings["kickside.ui\0logo_url"].value, branding.url())
        end)
    end)
end
return {run = test.run_cases(define_tests)}
