local test = require("test")
local readiness = require("readiness")
local time = require("time")

return {run = test.run_cases(function()
    test.describe("HTTP lifecycle readiness", function()
        test.it("uses native supervisor state before dispatch", function()
            readiness.await_running("app:gateway", readiness.deadline(10))
        end)

        test.it("returns only the request time left after readiness", function()
            local deadline = readiness.deadline(10)
            time.sleep("20ms")
            readiness.await_running("app:gateway", deadline)
            local remaining = assert(tonumber(assert(readiness.remaining_timeout(deadline):match("^(%d+)ms$"))))
            test.is_true(remaining > 0)
            test.is_true(remaining < 10000)
        end)

        test.it("reports a terminal service state without waiting", function()
            local ok, err = pcall(function()
                readiness.await_running("app:failed_gateway", readiness.deadline(10))
            end)
            test.is_false(ok)
            test.contains(tostring(err), "supervisor reports terminal service state")
            test.contains(tostring(err), "status=failed")
            test.contains(tostring(err), "desired=running")
        end)

        test.it("does not dispatch after the original deadline expires", function()
            local ok, err = pcall(function()
                readiness.remaining_timeout(readiness.deadline(0))
            end)
            test.is_false(ok)
            test.contains(tostring(err), "request deadline expires before dispatch")
        end)

        test.it("preserves supervisor query errors", function()
            local ok, err = pcall(function()
                readiness.await_running("", readiness.deadline(10))
            end)
            test.is_false(ok)
            test.contains(tostring(err), "supervisor state query failed")
            test.contains(tostring(err), "service ID required")
        end)
    end)
end)}
