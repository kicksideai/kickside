local test = require("test")
local phases = require("phases")
local fixture = require("fixture")
local function define_tests()
    test.describe("load slot quiescence", function()
        test.before_each(function() fixture.reset() end)
        test.it("waits for every control acknowledgement, running lease and due schedule before disabling once", function()
            phases.pause_event_slots("source-thread")
            test.eq(fixture.disables, 1)
            test.is_true(fixture.status_reads >= 4)
            test.is_true(fixture.reads >= 7)
            test.eq(fixture.calls[1], "status:a")
            test.eq(fixture.calls[#fixture.calls - 2], "disable")
            test.eq(fixture.calls[#fixture.calls - 1], "job:job-a")
            test.eq(fixture.calls[#fixture.calls], "job:job-b")
        end)
        test.it("propagates a Jobs read failure before mutating the fixture", function()
            fixture.read_error = "job store unavailable"
            local ok, err = pcall(phases.pause_event_slots, "source-thread")
            test.is_false(ok)
            test.is_true(string.find(tostring(err), fixture.read_error, 1, true) ~= nil)
            test.eq(fixture.disables, 0)
        end)
    end)
end
return test.run_cases(define_tests)
