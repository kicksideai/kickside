local test = require("test")
local delivery = require("delivery")
local fixture = require("fixture")
local support = require("support")
local function define_tests()
    test.describe("load fixture delivery contract", function()
        test.before_each(function() support.setup() end)
        test.it("answers delivery keys while receipts retain source item keys", function()
            local result, err = delivery.deliver_event({
                drive = {automation_id = "automation", drive_key = "main"},
                items = {{item_key = "source-1", delivery_key = "delivery-1"},
                         {item_key = "source-2", delivery_key = "delivery-2"}},
            })
            test.is_nil(err, tostring(err))
            test.eq(result.delivered_items[1].key, "delivery-1")
            test.eq(result.delivered_items[2].key, "delivery-2")
            local rows = support.query("SELECT item_key FROM kickside_lod_provider_receipt ORDER BY item_key")
            test.eq(rows[1].item_key, "source-1")
            test.eq(rows[2].item_key, "source-2")
            test.eq(support.query("SELECT item_count FROM kickside_lod_page_observation")[1].item_count, 2)
        end)
        test.it("answers retriable provider failures by delivery key without writing receipts", function()
            support.state_set("provider_outage", "1")
            local result, err = delivery.deliver_event({items = {{item_key = "source", delivery_key = "delivery"}}})
            test.is_nil(err, tostring(err))
            test.eq(result.failed_items[1].key, "delivery")
            test.eq(result.failed_items[1].error.kind, "Unavailable")
            test.is_true(result.failed_items[1].error.retriable)
            test.eq(#result.delivered_items, 0)
            test.eq(#support.query("SELECT item_key FROM kickside_lod_provider_receipt"), 0)
        end)
        test.it("updates a source receipt when a new delivery key redelivers the same item", function()
            for _, key in ipairs({"delivery-1", "delivery-2"}) do
                local result, err = delivery.deliver_event({drive = {automation_id = "automation", drive_key = "main"},
                    items = {{item_key = "source", delivery_key = key}}})
                test.is_nil(err, tostring(err))
                test.eq(result.delivered_items[1].key, key)
            end
            local receipts = support.query("SELECT item_key FROM kickside_lod_provider_receipt")
            test.eq(#receipts, 1)
            test.eq(receipts[1].item_key, "source")
        end)
        test.it("returns empty partitions for an empty page", function()
            local result, err = delivery.deliver_event({items = {}})
            test.is_nil(err, tostring(err))
            for _, name in ipairs({"delivered_items", "skipped_items", "waiting_items", "uncertain_items", "failed_items"}) do
                test.eq(#result[name], 0)
            end
        end)
        test.it("declares an event automation with one source", function()
            local result, err = fixture.install_event({thread_id = "thread", timer_count = 8})
            test.is_nil(err, tostring(err))
            test.eq(result.source.source_kind, "event")
            test.eq(result.source.source_thread_id, "thread")
            test.is_nil(result.schedules)
        end)
        test.it("declares interval automations with their own timer source", function()
            test.eq(type(fixture.install_timer), "function")
            local result, err = fixture.install_timer({})
            test.is_nil(err, tostring(err))
            test.eq(result.source.source_kind, "timer")
            test.eq(result.source.schedule.type, "interval")
            test.eq(result.source.schedule.expression, "5m")
            test.is_nil(result.schedules)
        end)
    end)
end
return test.run_cases(define_tests)
