local test = require("test")
local probe = require("probe")
local fixture = require("fixture")
local function define_tests()
    test.describe("load dispatcher round observation", function()
        test.before_each(function() fixture.reset() end)
        test.it("wakes slots and observes dispatcher completion before recording every sample", function()
            local result = probe.run()
            test.eq(result.samples, 20)
            test.eq(fixture.wakes, 20)
            test.eq(fixture.completions, 20)
            test.eq(fixture.inserts, 20)
            test.is_true(fixture.reads >= 80)
        end)
        test.it("propagates a public Jobs read failure", function()
            fixture.read_error = "Jobs read unavailable"
            local ok, err = pcall(probe.run)
            test.is_false(ok)
            test.is_true(tostring(err):find(fixture.read_error, 1, true) ~= nil)
            test.eq(fixture.inserts, 0)
        end)
        test.it("propagates a public Jobs wake failure", function()
            fixture.wake_error = "Jobs wake unavailable"
            local ok, err = pcall(probe.run)
            test.is_false(ok)
            test.is_true(tostring(err):find(fixture.wake_error, 1, true) ~= nil)
            test.eq(fixture.completions, 0)
        end)
    end)
end
return test.run_cases(define_tests)
