local test = require("test")
local uuid = require("uuid")
local security = require("security")
local funcs = require("funcs")
local store = require("store")
local workflow = require("workflow")
local types = require("types")

local function call_as(actor, input)
    local policy, policy_err = security.policy("app:workflows_suite_policy")
    test.is_nil(policy_err)
    local scope, scope_err = security.new_scope({ policy })
    test.is_nil(scope_err)
    local principal, actor_err = security.new_actor(actor, {})
    test.is_nil(actor_err)
    local result, call_err = funcs.new():with_actor(principal):with_scope(scope)
        :call("app:access_seam", input)
    test.is_nil(call_err)
    return result
end

local function count(db, table_name, field, value)
    local rows, err = db:query("SELECT COUNT(*) AS n FROM " .. table_name .. " WHERE " .. field .. "=$1", { value })
    test.is_nil(err)
    return tonumber(rows[1].n)
end

local function run_id_for(db, workflow_id)
    local run_id = uuid.v4()
    local _, run_err = db:execute([[INSERT INTO workflow_runs
        (run_id,workflow_id,version,trigger_kind,status,started_at,finished_at)
        VALUES ($1,$2,1,'manual','completed','2000-01-01T00:00:00Z','2000-01-01T00:00:00Z')]],
        { run_id, workflow_id })
    test.is_nil(run_err)

    return run_id
end

local function define_tests()
    test.describe("workflow owner GC", function()
        test.it("purges definition history with its owner rows", function()
            local id = uuid.v4()
            local _, edit_err = workflow.apply(id, { {
                type = types.COMMAND.PARAM_SET, body = { key = "owned", value = true },
            } }, "tester")
            test.is_nil(edit_err, tostring(edit_err))
            local purged, purge_err = store.purge(id)
            test.is_nil(purge_err, tostring(purge_err))
            test.is_true(purged)
            local db = assert(store.open_db())
            local events = assert(db:query("SELECT seq FROM workflow_def_events WHERE workflow_id=$1", { id }))
            db:release()
            test.eq(#events, 0)
        end)

        test.it("deletes workflow versions in bounded owner pages with typed continuation", function()
            local actor = "workflow-paged-gc-" .. tostring(uuid.v4())
            local owned = call_as(actor, { op = "create", title = "Paged GC" })
            test.is_nil(owned.error)
            local db = assert(store.open_db())
            for version = 1, 205 do
                local _, insert_err = db:execute([[INSERT INTO workflow_versions
                    (workflow_id,version,def_seq,created_at)
                    VALUES ($1,$2,0,'2000-01-01T00:00:00Z')]], { owned.id, version })
                test.is_nil(insert_err, tostring(insert_err))
            end
            db:release()
            local first, first_err = workflow.purge(owned.id)
            db = assert(store.open_db())
            local after_first = count(db, "workflow_versions", "workflow_id", owned.id)
            db:release()
            local second, second_err = workflow.purge(owned.id)
            local third, third_err = workflow.purge(owned.id)
            local removed = call_as(actor, { op = "delete", id = owned.id })
            test.is_false(first)
            test.is_true(errors.is(first_err, errors.CONFLICT), tostring(first_err))
            test.is_true((first_err :: any):details().cleanup_pending)
            test.is_true(after_first >= 105, "one call must delete at most 100 versions")
            test.is_false(second)
            test.is_true(errors.is(second_err, errors.CONFLICT), tostring(second_err))
            test.is_true(third, tostring(third_err))
            test.is_true(removed.success, tostring(removed.error))
        end)
        test.it("rejects a missing workflow state query result", function()
            local fake = { query = function() return nil, nil end }
            local rows, err = (store._internals :: any).query(fake, "SELECT 1", {})
            test.is_nil(rows)
            test.not_nil(err)
        end)
        test.it("reports active-run purge refusal as a typed conflict", function()
            local actor = "workflow-purge-error-" .. tostring(os.time())
            local owned = call_as(actor, { op = "create", title = "Active run" })
            test.is_nil(owned.error)
            local db, db_err = store.open_db()
            test.is_nil(db_err)
            local run_id = uuid.v4()
            local _, insert_err = db:execute([[INSERT INTO workflow_runs
                (run_id,workflow_id,version,trigger_kind,status,started_at)
                VALUES ($1,$2,1,'manual','running','2000-01-01T00:00:00Z')]],
                { run_id, owned.id })
            db:release()
            test.is_nil(insert_err)
            db = assert(store.open_db())
            db:release()
            local purged, purge_err = store.purge(owned.id)
            test.is_false(purged)
            test.is_true(errors.is(purge_err, errors.CONFLICT), tostring(purge_err))
            db = assert(store.open_db())
            test.eq(count(db, "workflow_runs", "run_id", run_id), 1)
            local _, delete_err = db:execute("DELETE FROM workflow_runs WHERE run_id=$1", { run_id })
            db:release()
            test.is_nil(delete_err)
            test.is_true(call_as(actor, { op = "delete", id = owned.id }).success)
        end)
        test.it("keeps a terminal run until its lifecycle event is published", function()
            local actor = "workflow-pending-event-" .. tostring(os.time())
            local owned = call_as(actor, { op = "create", title = "Pending event" })
            test.is_nil(owned.error)
            local db = assert(store.open_db())
            local run_id = uuid.v4()
            local _, insert_err = db:execute([[INSERT INTO workflow_runs
                (run_id,workflow_id,version,trigger_kind,status,started_at,finished_at,
                 terminal_event_pending,terminal_event_check_at)
                VALUES ($1,$2,1,'manual','completed','2000-01-01T00:00:00Z',
                    '2000-01-01T00:00:00Z',TRUE,'2999-01-01T00:00:00Z')]],
                { run_id, owned.id })
            db:release()
            test.is_nil(insert_err)
            db = assert(store.open_db())
            db:release()
            local purged, purge_err = store.purge(owned.id)
            db = assert(store.open_db())
            local retained = count(db, "workflow_runs", "run_id", run_id)
            local _, settle_err = db:execute("UPDATE workflow_runs SET terminal_event_pending=FALSE WHERE run_id=$1",
                { run_id })
            db:release()
            test.is_nil(settle_err)
            local deleted = call_as(actor, { op = "delete", id = owned.id })
            test.is_true(deleted.success)
            test.is_false(purged)
            test.is_true(errors.is(purge_err, errors.CONFLICT), tostring(purge_err))
            test.eq(retained, 1)
        end)
        test.it("component delete removes terminal runs only for its workflow", function()
            local actor = "workflow-gc-" .. tostring(os.time())
            local owned = call_as(actor, { op = "create", title = "GC owned" })
            local other = call_as(actor, { op = "create", title = "GC other" })
            test.is_nil(owned.error)
            test.is_nil(other.error)
            test.not_nil(owned.id)
            test.not_nil(other.id)
            local db, db_err = store.open_db()
            test.is_nil(db_err)
            local owned_run = run_id_for(db, owned.id)
            local other_run = run_id_for(db, other.id)
            db:release()

            local deleted = call_as(actor, { op = "delete", id = owned.id })
            test.is_nil(deleted.error)
            test.is_true(deleted.success)
            db, db_err = store.open_db()
            test.is_nil(db_err)
            test.eq(count(db, "workflow_runs", "run_id", owned_run), 0)
            test.eq(count(db, "workflow_runs", "run_id", other_run), 1)
            db:release()
            local cleanup = call_as(actor, { op = "delete", id = other.id })
            test.is_true(cleanup.success)
        end)

        test.it("component delete removes published versions only for its workflow", function()
            local actor = "workflow-version-gc-" .. tostring(os.time())
            local owned = call_as(actor, { op = "create", title = "Version owned" })
            local other = call_as(actor, { op = "create", title = "Version other" })
            test.is_nil(owned.error)
            test.is_nil(other.error)
            local db, db_err = store.open_db()
            test.is_nil(db_err)
            for _, id in ipairs({ owned.id, other.id }) do
                local _, err = db:execute([[INSERT INTO workflow_versions
                    (workflow_id,version,def_seq,created_at)
                    VALUES ($1,1,0,'2000-01-01T00:00:00Z')]], { id })
                test.is_nil(err)
            end
            db:release()

            local deleted = call_as(actor, { op = "delete", id = owned.id })
            test.is_nil(deleted.error)
            test.is_true(deleted.success)
            db, db_err = store.open_db()
            test.is_nil(db_err)
            test.eq(count(db, "workflow_versions", "workflow_id", owned.id), 0)
            test.eq(count(db, "workflow_versions", "workflow_id", other.id), 1)
            db:release()
            test.is_true(call_as(actor, { op = "delete", id = other.id }).success)
        end)

        test.it("component delete removes definition events only for its workflow", function()
            local actor = "workflow-event-gc-" .. tostring(os.time())
            local owned = call_as(actor, { op = "create", title = "Event owned" })
            local other = call_as(actor, { op = "create", title = "Event other" })
            test.is_nil(owned.error)
            test.is_nil(other.error)
            for _, id in ipairs({ owned.id, other.id }) do
                local _, err = workflow.apply(id, { {
                    type = types.COMMAND.PARAM_SET, body = { key = "gc", value = true },
                } }, "tester")
                test.is_nil(err, tostring(err))
            end

            local deleted = call_as(actor, { op = "delete", id = owned.id })
            test.is_nil(deleted.error)
            test.is_true(deleted.success)
            local db, db_err = store.open_db()
            test.is_nil(db_err)
            test.eq(count(db, "workflow_def_events", "workflow_id", owned.id), 0)
            test.eq(count(db, "workflow_def_events", "workflow_id", other.id), 1)
            db:release()
            test.is_true(call_as(actor, { op = "delete", id = other.id }).success)
        end)
    end)
end

return test.run_cases(define_tests)
