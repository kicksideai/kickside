local group_resolver = require("group_resolver")
local scope_writer = require("scope_writer")
local trigger_reconcile = require("trigger_reconcile")
local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local scopes = require("scopes")
local projection = require("projection")

local function invalid(err)
    test.is_true(errors.is(err, errors.INVALID))
    test.eq(err:retryable(), false)
end

local function define_tests()
    test.describe("native security persistence failures", function()
        local projector
        test.before_all(function() projector = scope_writer.start_projector() end)
        test.after_all(function() scope_writer.stop_projector(projector) end)

        test.it("reports native scope input errors", function()
            local _, get_err = scopes.get("")
            invalid(get_err)
            local _, missing_err = scopes.upsert({slug = ""}, "tester")
            invalid(missing_err)
            local _, malformed_err = scopes.upsert({slug = "bad slug"}, "tester")
            invalid(malformed_err)
            local result, delete_err = scopes.delete("")
            test.is_false(result)
            invalid(delete_err)
        end)
        test.it("reports native scope membership input errors", function()
            for _, value in ipairs({false, {false}, {""}}) do
                local _, err = group_resolver.resolve(value)
                invalid(err)
            end
            local _, empty_err = projection.group_set({})
            invalid(empty_err)
            local _, missing_err = projection.group_set(false)
            invalid(missing_err)
        end)
        for _, raw in ipairs({"{", "false", "7", '"text"', "null"}) do
            test.it("refuses corrupt stored scope policies without rewriting them: " .. raw, function()
                local db = assert(sql.get("app:db"))
                local slug = "native_policies_" .. uuid.v7():gsub("-", "")
                local _, insert_err = db:execute([[INSERT INTO kickside_security_scopes
                    (slug,label,description,policies,target,internal,enabled,created_at,updated_at)
                    VALUES ($1,'','','','','0','1','before','before')]], {slug})
                test.is_nil(insert_err)
                local _, seed_err = db:execute("UPDATE kickside_security_scopes SET policies=$1 WHERE slug=$2", {raw, slug})
                test.is_nil(seed_err)
                local ok, check_err = pcall(function()
                    local row, err = scopes.get(slug)
                    test.is_nil(row)
                    test.is_true(errors.is(err, errors.INTERNAL))
                    test.eq(err:retryable(), false)
                    test.eq(err:details().code, "persisted_data")
                    test.eq(err:details().field, "kickside_security_scopes.policies")
                    local reconciled, reconcile_err = trigger_reconcile.trigger()
                    test.is_nil(reconciled)
                    test.is_true(errors.is(reconcile_err, errors.INTERNAL))
                    test.eq(reconcile_err:retryable(), false)
                    test.eq(reconcile_err:details().code, "persisted_data")
                    local _, list_err = scopes.list()
                    test.is_true(errors.is(list_err, errors.INTERNAL))
                    local rows, read_err = db:query("SELECT policies,updated_at FROM kickside_security_scopes WHERE slug=$1", {slug})
                    test.is_nil(read_err)
                    test.eq(rows[1].policies, raw)
                    test.eq(rows[1].updated_at, "before")
                end)
                local _, delete_err = db:execute("DELETE FROM kickside_security_scopes WHERE slug=$1", {slug})
                test.is_nil(delete_err)
                db:release()
                if not ok then error(check_err) end
            end)
            test.it("preserves retired group-set data without using it: " .. raw, function()
                local db = assert(sql.get("app:db"))
                local name = "native_group_set_" .. uuid.v7()
                local _, seed_err = db:execute("INSERT INTO kickside_security_group_sets (scope_name,groups_json) VALUES ($1,$2)", {name, raw})
                test.is_nil(seed_err)
                local ok, check_err = pcall(function()
                    local reconciled, reconcile_err = trigger_reconcile.trigger()
                    test.is_nil(reconcile_err)
                    test.not_nil(reconciled)
                    local stored, read_err = db:query("SELECT groups_json FROM kickside_security_group_sets WHERE scope_name=$1", {name})
                    test.is_nil(read_err)
                    test.eq(stored[1].groups_json, raw)
                end)
                local _, delete_err = db:execute("DELETE FROM kickside_security_group_sets WHERE scope_name=$1", {name})
                test.is_nil(delete_err)
                db:release()
                if not ok then error(check_err) end
            end)
        end
    end)
end
return {run = test.run_cases(define_tests)}
