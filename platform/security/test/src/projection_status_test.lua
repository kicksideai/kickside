local test = require("test")
local registry = require("registry")
local security = require("security")
local funcs = require("funcs")
local projection = require("scope_projection")
local sql = require("sql")
local group_sets = require("group_sets")

local function read(allowed, groups)
    local actor = assert(security.new_actor("projection-status-admin", {security_groups = groups or {"app.security:user"}}))
    local policy = assert(security.policy("app.security:test_admin"))
    local policies = {policy}
    if not allowed then
        policies[#policies + 1] = assert(security.policy("app:projection_status_deny"))
    end
    local scope = assert(security.new_scope(policies))
    return funcs.new():with_actor(actor):with_scope(scope):call("app:projection_status_probe")
end

local function define_tests()
    test.describe("security projection status", function()
        test.it("reads live native revisions while preserving legacy materialization", function()
            local original = assert(registry.current_version())
            local ok, failure = pcall(function()
                test.not_nil(assert(projection.materialize({"app.security:user"})))
                local result = assert(read(true))
                test.eq(result.status, 200)
                test.is_true(result.body.current)
                local changes = assert(registry.snapshot()):changes()
                changes:create({id = "app:projection_status_policy", kind = "security.policy",
                    data = {groups = {"app.security:user"}, policy = {actions = "read", resources = "example:*", effect = "allow"}}})
                test.not_nil(assert(changes:apply()))
                local before = assert(registry.current_version()):id()
                result = assert(read(true))
                test.eq(result.status, 200)
                test.is_true(result.body.current)
                test.is_false(assert(projection.group_set({"app.security:user"})).current)
                test.eq(assert(registry.current_version()):id(), before)
                test.not_nil(assert(projection.reconcile()))
                result = assert(read(true))
                test.eq(result.status, 200)
                test.is_true(result.body.current)
            end)
            test.not_nil(assert(registry.apply_version(original)))
            if not ok then error(failure) end
        end)
        test.it("reports native groups current without registering a legacy group set", function()
            local groups = {"app:projection_status_native"}
            local name = assert(group_sets.name_for(groups))
            local original = assert(registry.current_version())
            local ok, failure = pcall(function()
                local changes = assert(registry.snapshot()):changes()
                changes:create({id = groups[1] .. "_policy", kind = "security.policy", data = {
                    groups = groups, policy = {actions = "read", resources = "native:*", effect = "allow"}}})
                assert(changes:apply())
                local version = assert(registry.current_version()):id()
                local result = assert(read(true, groups))
                test.eq(result.status, 200)
                test.is_true(result.body.current, "native group authority is available without materialization")
                test.eq(result.body.scope_name, name)
                test.eq(assert(registry.current_version()):id(), version)
                local db = assert(sql.get("app:db"))
                local rows, err = db:query("SELECT scope_name FROM kickside_security_group_sets WHERE scope_name=$1", {name})
                db:release()
                test.is_nil(err)
                test.eq(#rows, 0)
            end)
            assert(registry.apply_version(original))
            if not ok then error(failure) end
        end)
        test.it("propagates unavailable native authority without creating a scope", function()
            local before = assert(registry.current_version()):id()
            local result = assert(read(true, {"app:projection_status_missing"}))
            test.eq(result.status, 500)
            test.is_false(result.body.success)
            local _, native_err = security.named_scope("app:projection_status_missing")
            test.not_nil(native_err)
            test.eq(result.body.kind, native_err:kind())
            test.eq(result.body.retryable, native_err:retryable())
            test.eq(result.body.error, tostring(native_err))
            test.eq(assert(registry.current_version()):id(), before)
        end)
        test.it("requires endpoint access", function()
            local result, err = read(false)
            test.is_nil(err)
            test.eq(result.status, 403)
            test.is_false(result.body.success)
        end)
    end)
end

return test.run_cases(define_tests)
