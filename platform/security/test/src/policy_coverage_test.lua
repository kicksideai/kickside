local test = require("test")
local coverage = require("policy_coverage")
local function allow(actions, resources, excluded)
    return {effect = "allow", actions = actions, resources = resources,
        conditions = excluded and {{field = "action", operator = "nin", value = excluded}} or nil}
end
local function reduced(before, after)
    local change, err = coverage.compare_rules(before, after)
    test.is_nil(err); return change.reduced
end
return {run = test.run_cases(function()
    test.describe("combined policy coverage", function()
        test.it("recognizes coverage split across policies", function()
            test.is_false(reduced({allow({"read", "write"}, {"a", "b"})}, {
                allow("read", {"a", "b"}), allow("write", "a"), allow("write", "b")}))
        end)
        test.it("retains a conditional wildcard cover when its excluded actions remain absent", function()
            local cover = allow("*", "*", {"private.read"})
            test.is_false(reduced({cover, allow("public.read", "a")}, {cover}))
            test.is_true(reduced({cover, allow("private.read", "a")}, {cover}))
        end)
        test.it("checks action patterns against exclusions conservatively", function()
            local cover = allow("*", "*", {"private.read"})
            test.is_false(reduced({cover, allow("public.*", "a")}, {cover}))
            test.is_true(reduced({cover, allow("private.*", "a")}, {cover}))
        end)
        test.it("requires action prefixes to cover the whole previous grant", function()
            test.is_false(reduced({allow("tools.read", "a")}, {allow("tools.*", "a")}))
            test.is_true(reduced({allow("toolshed.read", "a")}, {allow("tools.*", "a")}))
            test.is_true(reduced({allow("*", "a")}, {allow("tools.*", "a")}))
        end)
        test.it("keeps unmatched constraints and new denies fenced", function()
            local constrained = allow("read", "a")
            constrained.conditions = {{field = "actor.id", operator = "eq", value = "subject"}}
            test.is_true(reduced({allow("read", "a")}, {constrained}))
            test.is_true(reduced({allow("*", "*")}, {allow("*", "*"), {effect = "deny", actions = "read", resources = "a"}}))
        end)
        test.it("proves resource prefix coverage without covering adjacent namespaces or wider patterns", function()
            test.is_false(reduced({allow("read", "documents:one")}, {allow("read", "documents:*")}))
            test.is_false(reduced({allow("read", "documents:folder:*")}, {allow("read", "documents:*")}))
            test.is_true(reduced({allow("read", "documents_extra:one")}, {allow("read", "documents:*")}))
            test.is_true(reduced({allow("read", "*")}, {allow("read", "documents:*")}))
            test.is_true(reduced({allow("read", "documents:*")}, {allow("read", "documents:folder:*")}))
            test.is_true(reduced({allow("write", "documents:one")}, {allow("read", "documents:*")}))
        end)
        test.it("proves unknown earlier grants only under unrestricted current coverage", function()
            test.is_false(reduced({allow("*", "*")}, {allow("*", "*")}))
            test.is_true(reduced({allow("*", "*")}, {allow("*", "*", {"private.read"})}))
        end)
    end)
end)}
