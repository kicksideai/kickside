local test = require("test")
local state = require("state")
local fixture = require("fixture")
local subject = require("subject")

return test.run_cases(function()
    test.describe("transfer upload staging errors", function()
        test.before_each(function() state.reset(); fixture.body = nil; fixture.status = nil end)
        test.it("stops before writing when parent creation fails", function()
            subject.handler()
            test.eq(state.counters().written, 0)
            test.eq(fixture.status, 500)
        end)
        test.it("returns a native cleanup error after import", function()
            state.allow_mkdir()
            local source = errors.new({ kind = errors.UNAVAILABLE, retryable = true,
                message = "upload cleanup unavailable", details = { marker = "remove" } })
            state.reject_remove(source)
            local result, err = subject.handler()
            test.is_nil(result)
            test.eq(err, source)
            test.is_nil(fixture.body)
        end)
        test.it("returns a native cleanup error after a write failure", function()
            state.allow_mkdir()
            state.reject("write", errors.new({ kind = errors.UNAVAILABLE, message = "write unavailable" }))
            local source = errors.new({ kind = errors.PERMISSION_DENIED, retryable = false,
                message = "upload cleanup refused", details = { marker = "remove" } })
            state.reject_remove(source)
            local result, err = subject.handler()
            test.is_nil(result)
            test.eq(err, source)
            test.is_nil(fixture.body)
        end)
        test.it("retains a write failure when no upload file exists", function()
            state.allow_mkdir()
            state.absent_staging()
            state.reject("write", errors.new({ kind = errors.UNAVAILABLE, message = "upload write unavailable" }))
            subject.handler()
            test.eq(fixture.status, 500)
            test.contains(fixture.body.error, "upload write unavailable")
            test.eq(state.counters().removed, 0)
        end)
        test.it("imports and removes the staged upload before reporting success", function()
            state.allow_mkdir()
            subject.handler()
            test.eq(fixture.status, 200)
            test.is_true(fixture.body.success)
            test.eq(state.counters().written, 1)
            test.eq(state.counters().removed, 1)
        end)
    end)
end)
