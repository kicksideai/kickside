local test = require("test")
local refresh_schedule = require("refresh_schedule")
local function define_tests()
    test.describe("OAuth refresh deadlines", function()
        test.it("computes the exact refresh deadline without rounding to an interval", function()
            local deadline, err = refresh_schedule.deadline(4601, 1000)
            test.is_nil(err, tostring(err))
            test.eq(deadline, "1970-01-01T01:01:40Z")
        end)
        test.it("schedules already expired tokens at their actual past deadline", function()
            local deadline, err = refresh_schedule.deadline(100, 200)
            test.is_nil(err)
            test.eq(deadline, "1970-01-01T00:02:05Z")
        end)
        test.it("rejects invalid timestamps and leaves non-expiring tokens unarmed", function()
            local deadline, err = refresh_schedule.deadline("invalid", 1000)
            test.is_nil(deadline); test.not_nil(err)
            deadline, err = refresh_schedule.deadline(nil, 1000)
            test.is_nil(deadline); test.is_nil(err)
        end)
    end)
end
return test.run_cases(define_tests)
