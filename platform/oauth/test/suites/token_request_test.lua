local test = require("test")
local request = require("request")
local json = require("json")
local base64 = require("base64")
local function cases()
    test.describe("OAuth token endpoint protocols", function()
        test.it("retains the existing form client_secret_post default", function()
            local options, err = request.build({grant_type = "authorization_code", client_id = "id", client_secret = "s&=+", code = "a/b"})
            test.is_nil(err); test.eq(options.headers["Content-Type"], "application/x-www-form-urlencoded")
            test.ok(options.body:find("client_secret=s%26%3D%2B", 1, true) ~= nil)
            test.is_nil(options.headers.Authorization)
        end)
        test.it("builds Notion JSON requests with Basic credentials outside the body", function()
            local original = {grant_type = "authorization_code", client_id = "id", client_secret = "secret", code = "notion-code", redirect_uri = "https://app.example/callback"}
            local options, err = request.build(original, "client_secret_basic", "json")
            test.is_nil(err); test.eq(options.headers["Content-Type"], "application/json")
            test.eq(base64.decode(options.headers.Authorization:sub(7)), "id:secret")
            local body = json.decode(options.body)
            test.eq(body.code, "notion-code"); test.is_nil(body.client_id); test.is_nil(body.client_secret)
            test.eq(original.client_secret, "secret"); test.eq(options.timeout, "15s"); test.eq(options.max_response_body, 1048576)
        end)
        test.it("builds Airtable form refresh requests with Basic credentials and PKCE exchange values", function()
            local options, err = request.build({grant_type = "refresh_token", client_id = "id+", client_secret = "s&", refresh_token = "r/+="}, "client_secret_basic", "form")
            test.is_nil(err); test.eq(base64.decode(options.headers.Authorization:sub(7)), "id%2B:s%26")
            test.ok(options.body:find("refresh_token=r%2F%2B%3D", 1, true) ~= nil)
            test.is_nil(options.body:find("client_secret", 1, true))
            local exchange = request.build({grant_type = "authorization_code", client_id = "id", client_secret = "secret", code_verifier = "verifier"}, "client_secret_basic", "form")
            test.ok(exchange.body:find("code_verifier=verifier", 1, true) ~= nil)
        end)
        test.it("rejects unsupported protocol settings instead of silently falling back", function()
            for _, pair in ipairs({{"password", "form"}, {"client_secret_post", "xml"}, {"client_secret_basic", "json"}}) do
                local options, err = request.build({}, pair[1], pair[2])
                test.is_nil(options); test.is_true(errors.is(err, errors.INVALID))
            end
        end)
    end)
end
return {run = test.run_cases(cases)}
