-- Fixed ciphertext emitted by the previous implementation with the synthetic ab key.
local test = require("test")
local env = require("env")
local caller = require("caller")

return {run = test.run_cases(function()
    test.describe("stored ciphertext compatibility", function()
        test.it("reads ciphertext from the previous implementation through the environment key", function()
            local previous, env_err = env.get("ENCRYPTION_KEY")
            test.is_nil(env_err)
            local _, set_err = env.set("ENCRYPTION_KEY", string.rep("ab", 32))
            test.is_nil(set_err)
            local key, key_err = caller.get_encryption_key()
            local value, err = caller.decrypt_oauth_data("GlJl/G8tNkDbxuNL9+cS5jvnY4F2Xw2ibIlQFel8l/MMNuFN098aq7hUJ1jPatTLifTEFDeuyLKgbKZu/4//BCfKID4AwImyspMrZZhq", key :: string)
            local access, access_err = caller.decrypt_access_token("qabtEAT9Q6v/jM/v5iA4K9ppUveB3JrP9p8cFZpzUYe6xAh+/ua1Br3hFZICqvPk", key :: string)
            local _, restore_err = env.set("ENCRYPTION_KEY", previous)
            test.is_nil(restore_err)
            test.is_nil(err)
            test.is_nil(key_err)
            test.is_nil(access_err)
            test.eq(value.tokens.access_token, "oauth-fixture-secret")
            test.eq(access, "oauth-fixture-secret")
        end)
    end)
end)}
