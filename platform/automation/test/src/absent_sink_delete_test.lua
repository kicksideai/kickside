local test = require("test")
local component = require("component")
local automations = require("automations")
local deletion_worker = require("deletion_worker")
local sql = require("sql")
local uuid = require("uuid")
local registry = require("registry")
local drive = require("drive")
local slot = require("slot")

return test.run_cases(function()
    test.describe("automation deletion without an external sink", function()
        test.it("deletes a sync through its declared platform owner without resolving its sink", function()
            test.is_nil(registry.get("example.absent.sink:items"))
            local service = assert(component.get_service())
            local created, err = service:register({component_id = uuid.v7(), impl_id = "kickside.sync:sync",
                private_context = {sink = {port = "example.absent.sink:items", config = {}}},
                meta = {title = "Absent sink sync", class = "sync"}})
            test.is_nil(err, tostring(err))
            test.is_true(created.success, tostring(created.error))
            local id = created.component_id
            local db = assert(sql.get("app:db"))
            local tx = assert(db:begin())
            local _, drive_err = drive.insert_tx(tx, {automation_id = id, drive_key = "main",
                source_kind = "timer", applied = {}, applied_hash = "absent-sink"})
            test.is_nil(drive_err, tostring(drive_err))
            assert(tx:commit())
            assert(db:release())
            local job_id, slot_err = slot.enqueue(id, "main")
            test.is_nil(slot_err, tostring(slot_err))
            local accepted, delete_err = automations.delete_automation(id)
            test.is_nil(delete_err, tostring(delete_err))
            test.eq(accepted.status, "in_progress")
            local finished, finish_err = deletion_worker.run(id)
            test.is_nil(finish_err, tostring(finish_err))
            test.is_true(finished.deleted)
            db = assert(sql.get("app:db"))
            local rows = assert(db:query("SELECT component_id FROM kickside_components WHERE component_id=$1", {id}))
            local drives = assert(db:query("SELECT drive_key FROM kickside_automation_drive WHERE automation_id=$1", {id}))
            local jobs = assert(db:query("SELECT id FROM kickside_job WHERE id=$1", {job_id}))
            assert(db:release())
            test.eq(#rows, 0)
            test.eq(#drives, 0)
            test.eq(#jobs, 0)
        end)
    end)
end)
