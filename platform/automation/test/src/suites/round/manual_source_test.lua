local test = require("test")
local uuid = require("uuid")
local json = require("json")
local h = require("round_harness")
local drive = require("drive")

local TOOL = "kickside.automation.agent:automations_manage"

return {run = test.run_cases(function()
    test.describe("AUTOMATION-MANUAL-SOURCE durable explicit occurrences", function()
        local env
        local function source()
            local key = "manual-" .. uuid.v7()
            h.new_drive({automation_id = env.automation_id, drive_key = key, source_kind = "manual"})
            return key
        end
        local function control(key, action, request)
            local result, err = env.caller:call(TOOL, {action = "control", id = env.automation_id,
                drive_key = key, control = action, request_id = request or uuid.v7()})
            test.is_nil(err, tostring(err))
            test.eq(result.state, "succeeded")
            return result
        end
        local function run(key, seam)
            local result, err = env.run(env.automation_id, key, seam)
            test.is_nil(err, tostring(err))
            return result
        end
        test.before_all(function() env = h.setup("manual_source") end)
        test.it("parks without executing on install or resume", function()
            local key = source()
            run(key)
            control(key, "resume")
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 0)
            test.eq(h.read_drive(env.automation_id, key).event_seq, 0)
            test.eq(env.last_completion().options.record.status, "parked")
        end)
        test.it("admits one occurrence per explicit request and parks after consumption", function()
            local key = source()
            control(key, "run_now")
            test.eq(h.read_drive(env.automation_id, key).event_seq, 1)
            run(key)
            local rows = h.log_rows(env.automation_id, key)
            test.eq(#rows, 1)
            test.eq(rows[1].item_key, key .. ":1")
            test.eq(h.read_drive(env.automation_id, key).last_committed_occurrence_seq, 1)
            test.is_nil(h.read_drive(env.automation_id, key).occurrence_seq)
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 1)
            test.eq(env.last_completion().options.record.status, "parked")
        end)
        test.it("replays its command before and after consumption without enqueueing twice", function()
            local key, request = source(), uuid.v7()
            local first = control(key, "run_now", request)
            local replay = control(key, "run_now", request)
            test.eq(replay.generation, first.generation)
            test.eq(h.read_drive(env.automation_id, key).event_seq, 1)
            run(key)
            replay = control(key, "run_now", request)
            test.eq(replay.generation, first.generation)
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 1)
            test.eq(h.read_drive(env.automation_id, key).event_seq, 1)
        end)
        test.it("retains every queued request while paused and consumes them in sequence", function()
            local key = source()
            control(key, "pause")
            control(key, "run_now")
            control(key, "run_now")
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 0)
            test.eq(h.read_drive(env.automation_id, key).event_seq, 2)
            control(key, "resume")
            run(key); run(key); run(key)
            local rows = h.log_rows(env.automation_id, key)
            test.eq(#rows, 2)
            test.eq(rows[1].item_key, key .. ":1")
            test.eq(rows[2].item_key, key .. ":2")
            test.eq(h.read_drive(env.automation_id, key).last_committed_occurrence_seq, 2)
            test.eq(env.last_completion().options.record.status, "parked")
        end)
        test.it("retains the persisted occurrence across an acquisition failure", function()
            local key = source()
            control(key, "run_now")
            run(key, function(identity, target, args, options)
                if target == "kickside.automation:round_acquire" then
                    return nil, errors.new({kind = errors.UNAVAILABLE, retryable = true, message = "source unavailable"})
                end
                return env.run_as(identity, target, args, options)
            end)
            local stamped = h.read_drive(env.automation_id, key)
            test.eq(stamped.occurrence_seq, 1)
            test.eq(#h.log_rows(env.automation_id, key), 0)
            run(key)
            local rows = h.log_rows(env.automation_id, key)
            test.eq(#rows, 1)
            test.eq(rows[1].item_key, stamped.occurrence_key)
            test.eq(json.decode(rows[1].detail_json).fired_at, stamped.occurrence_due_at)
        end)
        test.it("never turns replay or resync into a new requested occurrence", function()
            local key = source()
            control(key, "run_now")
            run(key)
            control(key, "replay")
            control(key, "resync")
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 1)
            test.eq(h.read_drive(env.automation_id, key).event_seq, 1)
            test.eq(h.read_drive(env.automation_id, key).last_committed_occurrence_seq, 1)
        end)
        test.it("admits the next request above a retained consumed occurrence position", function()
            local key = source()
            h.exec("UPDATE kickside_automation_drive SET last_committed_occurrence_seq=3,event_seq=0 WHERE automation_id=$1 AND drive_key=$2",
                {env.automation_id, key})
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 0)
            control(key, "run_now")
            run(key)
            local rows = h.log_rows(env.automation_id, key)
            test.eq(#rows, 1)
            test.eq(rows[1].item_key, key .. ":4")
            test.eq(h.read_drive(env.automation_id, key).last_committed_occurrence_seq, 4)
            run(key)
            test.eq(#h.log_rows(env.automation_id, key), 1)
        end)
        test.it("preserves an outstanding stamped occurrence when admitting another request", function()
            local key = source()
            control(key, "run_now")
            run(key, function(identity, target, args, options)
                if target == "kickside.automation:round_acquire" then
                    return nil, errors.new({kind = errors.UNAVAILABLE, retryable = true, message = "source unavailable"})
                end
                return env.run_as(identity, target, args, options)
            end)
            h.exec("UPDATE kickside_automation_drive SET event_seq=0 WHERE automation_id=$1 AND drive_key=$2",
                {env.automation_id, key})
            control(key, "run_now")
            run(key); run(key); run(key)
            local rows = h.log_rows(env.automation_id, key)
            test.eq(#rows, 2)
            test.eq(rows[1].item_key, key .. ":1")
            test.eq(rows[2].item_key, key .. ":2")
            test.eq(h.read_drive(env.automation_id, key).last_committed_occurrence_seq, 2)
        end)
        test.it("keeps none-source drives without a slot or acquisition after run_now", function()
            local key = "main"
            control(key, "run_now")
            local row = h.read_drive(env.automation_id, key)
            test.eq(row.event_seq, 0)
            test.is_nil(row.job_id)
            test.is_nil(row.occurrence_seq)
        end)
    end)
end)}
