local test = require("test")
local funcs = require("funcs")
local security = require("security")
return { run = test.run_cases(function()
    test.describe("one-scope install", function()
        test.it("preserves administrator tool access", function()
            local scope, scope_err = security.named_scope("app:admin")
            test.is_nil(scope_err)
            local result, err = funcs.new():with_actor(security.new_actor("admin", {}))
                :with_scope(scope):call("kickside.self_reflection.traits:self_reflection_tool", { action = "overview" })
            test.is_nil(err)
            test.is_true(result.success)
        end)
        test.it("preserves discovery and denies tool execution for readers", function()
            local scope, scope_err = security.named_scope("app:reader")
            test.is_nil(scope_err)
            local exec = funcs.new():with_actor(security.new_actor("reader", {})):with_scope(scope)
            local result, err = exec:call("app:discovery_probe", {})
            test.is_nil(err)
            test.is_true(result.visible)
            test.is_true(result.leaked)
            test.not_nil(result.hidden)
            test.is_false(result.denied)
            local value, access_err = exec:call("kickside.self_reflection.traits:self_reflection_tool", { action = "overview" })
            test.is_nil(value)
            test.is_true(errors.is(access_err, errors.PERMISSION_DENIED))
        end)
    end)
end) }
