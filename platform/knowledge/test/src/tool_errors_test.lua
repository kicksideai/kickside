        test.it("KB discovery returns an error when its component service is unavailable", function()
            local original = component.get_service
            component.get_service = function() return nil, "discovery offline" end
            local result, err = kb_tools.find({}, {})
            component.get_service = original
            test.is_nil(result)
            test.is_true(errors.is(err, errors.INTERNAL))
            test.contains(tostring(err), "knowledge service unavailable")
        end)
        test.it("kickside.knowledge.traits:kb_query_tool rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.knowledge.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.knowledge.traits:kb_query_tool", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.INVALID), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("query is required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.knowledge.traits:kb_retrieve_tool rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.knowledge.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.knowledge.traits:kb_retrieve_tool", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.INVALID), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("query is required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.knowledge.traits:kb_embed_tool rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.knowledge.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.knowledge.traits:kb_embed_tool", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.INVALID), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("content is required", 1, true) ~= nil, tostring(err))
