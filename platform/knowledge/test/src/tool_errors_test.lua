        test.it("search and ask keep the classified kind and cause of a retrieval failure", function()
            local original_access, original_query, original_ask = component.validate_access, kb_search.query, kb_answer.ask
            component.validate_access = function() return true, nil end
            local failures = {
                errors.new({ kind = errors.UNAVAILABLE, message = "document analysis failed: Model failed to return valid JSON", retryable = true }),
                errors.new({ kind = errors.TIMEOUT, message = "model timed out" }),
            }
            local outcomes = {}
            for _, failure in ipairs(failures) do
                kb_search.query = function() return nil, failure end
                kb_answer.ask = function() return nil, failure end
                local _, search_err = kb_tools.search({ kb_id = "kb", query = "q" }, {})
                local _, ask_err = kb_tools.ask({ kb_id = "kb", query = "q" }, {})
                table.insert(outcomes, { failure, search_err, ask_err })
            end
            kb_search.query = function() return nil, "plain failure" end
            local _, plain_err = kb_tools.search({ kb_id = "kb", query = "q" }, {})
            component.validate_access, kb_search.query, kb_answer.ask = original_access, original_query, original_ask
            for _, outcome in ipairs(outcomes) do
                for index = 2, 3 do
                    local err = outcome[index]
                    test.not_nil(err)
                    test.eq(err:kind(), outcome[1]:kind())
                    test.eq(err:retryable(), outcome[1]:retryable())
                    test.contains(tostring(err), tostring(outcome[1]))
                end
            end
            test.is_true(errors.is(plain_err, errors.INTERNAL))
            test.contains(tostring(plain_err), "plain failure")
        end)
    end)
end

return { run = test.run_cases(define_tests) }
