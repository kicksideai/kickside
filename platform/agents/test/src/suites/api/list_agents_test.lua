local test = require("test")
local list_agents = require("list_agents")
local agents_by_name = require("agents_by_name")

local function define_tests()
    test.describe("agent discovery visibility", function()
        test.it("only exposes public system agents", function()
            test.is_true(list_agents.system_agent_visible({ public = true, class = "public" }, "public"))
            test.is_true(list_agents.system_agent_visible({ public = true, class = { "public", "keeper" } }, "public"))
            test.is_false(list_agents.system_agent_visible({ class = "public" }, "public"))
            test.is_false(list_agents.system_agent_visible({ class = { "public", "keeper" } }, "public"))
            test.is_false(list_agents.system_agent_visible({ class = "keeper" }, "public"))
            test.is_false(list_agents.system_agent_visible({ public = false, class = "public" }, "public"))
            test.is_false(list_agents.system_agent_visible({ public = "true", class = "public" }, "public"))
            test.is_false(list_agents.system_agent_visible({ public = 1, class = "public" }, "public"))
            test.is_false(list_agents.system_agent_visible({ public = true, private = true, class = "public" }, "public"))
            test.is_false(list_agents.system_agent_visible({ public = true, class = "admin" }, "public"))
            test.is_true(list_agents.system_agent_visible({ public = true, class = "system_onboarding", palette_hidden = true }, "system_onboarding"))
            test.is_false(list_agents.system_agent_visible({ public = true, class = "system_onboarding", palette_hidden = true }, "public"))
        end)

        test.it("only exposes explicitly public user agents", function()
            test.is_true(list_agents.user_agent_visible({ public = true }))
            test.is_true(list_agents.user_agent_visible({ public = "true" }))
            test.is_false(list_agents.user_agent_visible({}))
            test.is_false(list_agents.user_agent_visible({ public = false }))
            test.is_false(list_agents.user_agent_visible({ public = "false" }))
            test.is_false(list_agents.user_agent_visible({ public = 1 }))
            test.is_false(list_agents.user_agent_visible({ public = true, private = true }))
            test.is_false(list_agents.user_agent_visible({ public = "true", private = "true" }))
        end)

        test.it("title resolution only accepts public system agent entries", function()
            test.is_true(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", public = true } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", class = "public" } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", class = { "keeper", "public" } } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", class = "keeper" } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", public = false } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", public = "true" } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.gen1", public = true, private = true } }))
            test.is_false(agents_by_name.is_public_system_agent({ meta = { type = "agent.trait", public = true } }))
        end)

        test.it("carries explicit palette visibility metadata without title heuristics", function()
            local hidden = list_agents.palette_metadata({ palette_hidden = true, environment = "proof" })
            test.is_true(hidden.palette_hidden)
            test.eq(hidden.environment, "proof")
            test.is_true(list_agents.palette_metadata({ palette_hidden = "true" }).palette_hidden)
            test.is_true(list_agents.palette_metadata({ palette_hidden = 1 }).palette_hidden)
            local visible = list_agents.palette_metadata({ title = "Workflow Runner (demo)" })
            test.is_false(visible.palette_hidden)
            test.is_nil(visible.environment)
        end)
    end)
end

return { run = test.run_cases(define_tests) }
