local test = require("test")
local policy = require("policy")
local curator = require("curator")
local json = require("json")
local function define_tests()
    test.describe("model window checkpoint policy", function()
        test.it("reserves the completed and next outputs plus a safety margin", function()
            local spec, err = policy.apply({model = "checkpoint-small-model", max_tokens = 8000})
            test.is_nil(err)
            test.eq(spec.agent_options.checkpoint.token_threshold, 15091)
        end)
        test.it("retains the published session checkpoint cap", function()
            local spec, err = policy.apply({model = "checkpoint-policy-model", max_tokens = 8000})
            test.is_nil(err)
            test.eq(spec.agent_options.checkpoint.token_threshold, 50000,
                "the model ceiling must not raise the harness's declared session cap")
        end)
        test.it("keeps master context depth stable across repeated seeding", function()
            local traits = {{id = "kickside.agents.traits:trait_master", context = {namespaces = {"test"}}}}
            traits = curator.seed(traits, "agent:test")
            local baseline = #json.encode(traits)
            for _ = 1, 10 do traits = curator.seed(traits, "agent:test") end
            test.eq(#json.encode(traits), baseline)
            test.eq(traits[1].context.trait_contexts[traits[1].id].base_traits, nil)
        end)
        test.it("surfaces model selection errors without deriving a constant threshold", function()
            local spec, err = policy.apply({model = "unregistered-checkpoint-policy-model"})
            test.is_nil(spec)
            test.not_nil(err)
            test.is_true(errors.is(err, errors.NOT_FOUND))
            test.contains(tostring(err), "unregistered-checkpoint-policy-model")
        end)
    end)
end
local cases = test.run_cases(define_tests)
return {run = function(options) return cases(options) end}
