local test = require("test")
local agents = require("agents")
local state = require("state")
local function define_tests()
    test.describe("Agent context decision writes", function()
        test.it("preserves a concurrently attached memory target when detaching the earlier one", function()
            state.reset({ memory_target_id = "earlier" }, { memory_target_id = "concurrent" })
            local result, err = agents.detach_kb({ component_id = "agent", kb_id = "earlier" })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(err:details().reason, "version_mismatch")
            test.eq(state.context().memory_target_id, "concurrent")
        end)
        test.it("preserves concurrent tools when adding a capability", function()
            state.reset({ tools = {} }, { tools = { "concurrent" } })
            local result, err = agents.attach_tool({ component_id = "agent", tool_id = "app:public_tool_probe" })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(state.context().tools[1], "concurrent")
        end)
        test.it("rejects a trait edit when the validated context changes", function()
            state.reset({ traits = { "app:public_trait_probe" } }, { traits = {} })
            local result, err = agents.update({ component_id = "agent", trait_contexts = {} })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(#state.context().traits, 0)
        end)
        test.it("preserves concurrent capability changes when removing a tool", function()
            state.reset({ tools = { "earlier", "remaining" } }, { tools = { "earlier", "remaining", "concurrent" } })
            local result, err = agents.detach_tool({ component_id = "agent", tool_id = "earlier" })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.eq(#state.context().tools, 3)
            test.eq(state.context().tools[3], "concurrent")
        end)
    end)
end
return { run = test.run_cases(define_tests) }
