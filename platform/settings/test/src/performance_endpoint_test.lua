local test = require("test")
local funcs = require("funcs")
local process = require("process")
local channel = require("channel")
local time = require("time")
local jobs = require("jobs")
local security = require("security")
local function invoke(method, body)
    local responses = process.listen("performance.http.result")
    local policies = {}
    for _, id in ipairs({"kickside.settings.security:module_runtime", "kickside.core.jobs.security:module_access",
        "kickside.core.jobs.security:module_runtime", "kickside.settings.security:performance_admin",
        "kickside.settings.security:performance_policy_write", "app:performance_test_transport", "app:performance_test_database"}) do
        policies[#policies + 1] = assert(security.policy(id))
    end
    local _, err = funcs.new():with_actor(security.new_actor("performance-administrator", {}))
        :with_scope(security.new_scope(policies)):with_context({performance_body = body, performance_caller = tostring(process.pid())})
        :call("kickside.settings.api:" .. (method == "GET" and "get_performance" or "put_performance"))
    test.is_nil(err)
    local timeout = time.after("5s")
    local result = channel.select({responses:case_receive(), timeout:case_receive()})
    process.unlisten(responses)
    test.neq(result.channel, timeout)
    return result.value
end
local function await_state(ch, predicate)
    local timeout = time.after("5s")
    while true do
        local state = assert(jobs.get_pool_state())
        if predicate(state) then return state end
        local event = channel.select({ch:case_receive(), timeout:case_receive()})
        test.neq(event.channel, timeout, "owner publishes a durable applied state")
    end
end
local function start_owner(refused)
    local changed = process.listen("performance.invalidated")
    local pid = assert(process.with_context({performance_refused = refused == true, performance_observer = tostring(process.pid())})
        :spawn_linked_monitored("kickside.core.jobs.service:worker", "app:processes"))
    -- Wait for this boot's first invalidation, rather than trusting a previous
    -- owner's durable row or introducing a production request/reply protocol.
    local timeout = time.after("5s")
    local event = channel.select({changed:case_receive(), timeout:case_receive()})
    test.neq(event.channel, timeout)
    return pid, assert(jobs.get_pool_state()), changed
end
local function stop_owner(pid)
    assert(process.cancel(pid, "1s"))
    local timeout = time.after("5s")
    while true do
        local event = channel.select({process.events():case_receive(), timeout:case_receive()})
        test.neq(event.channel, timeout)
        if event.value.kind == process.event.EXIT and tostring(event.value.from) == tostring(pid) then return end
    end
end
return {run = test.run_cases(function()
    test.describe("Registered performance HTTP endpoints", function()
        test.it("reads effective policy and returns JSON from the real GET entry", function()
            local response = invoke("GET", "")
            test.eq(response.status, 200)
            test.eq(response.content_type, "application/json")
            test.eq(response.body.fields["proc.max_execution"].value, "10m")
            test.eq(response.body.fields["worker.count_postgres"].value, 4)
        end)
        test.it("preserves native validation classification from the real PUT entry", function()
            local response = invoke("PUT", '{"values":{"worker.count_sqlite":3}}')
            test.eq(response.status, 400)
            test.eq(response.body.kind, errors.INVALID)
            test.is_false(response.body.committed)
        end)
        test.it("rejects malformed JSON through the real PUT entry", function()
            local response = invoke("PUT", "invalid")
            test.eq(response.status, 400)
            test.eq(response.body.code, "performance_request_invalid")
        end)
        test.it("reports an offline committed policy as waiting for its next owner", function()
            local response = invoke("PUT", '{"values":{"worker.awaited_slots":2}}')
            test.eq(response.status, 200)
            test.is_true(response.body.committed)
            test.is_nil(response.body.applied)
            test.eq(response.body.fields["worker.awaited_slots"].source, "admin")
            test.eq(invoke("PUT", '{"values":{},"unset":["worker.awaited_slots"]}').status, 200)
        end)
        test.it("authorized PUT applies to the real owner and changes live slots", function()
            local pid, initial, changed = start_owner()
            local response = invoke("PUT", '{"values":{"worker.awaited_slots":2}}')
            test.eq(response.status, 200)
            test.is_true(response.body.committed)
            test.is_nil(response.body.applied, "the write does not await application")
            local state = await_state(changed, function(current) return current.applied_revision >= response.body.revision end)
            test.eq(state.awaited, 2)
            test.eq(state.total, initial.total + 1)
            stop_owner(pid)
            process.unlisten(changed)
            local successor, recovered, successor_changed = start_owner()
            test.eq(recovered.awaited, 2, "the successor reads the committed revision")
            test.eq(recovered.total, state.total)
            local read = invoke("GET", "")
            test.eq(read.body.pool.applied_revision, recovered.applied_revision, "status reads SQL without owner requests")
            invoke("PUT", '{"values":{},"unset":["worker.awaited_slots"]}')
            stop_owner(successor)
            process.unlisten(successor_changed)
        end)
        test.it("keeps commit and applied status independent of failed realtime delivery", function()
            local pid, _, changed = start_owner(true)
            local response = invoke("PUT", '{"values":{"worker.awaited_slots":2}}')
            test.eq(response.status, 200)
            test.is_true(response.body.committed)
            local state = await_state(changed, function(current) return current.applied_revision >= response.body.revision end)
            test.is_nil(state.apply_error)
            test.eq(state.awaited, 2)
            test.eq(invoke("GET", "").status, 200)
            invoke("PUT", '{"values":{},"unset":["worker.awaited_slots"]}')
            stop_owner(pid)
            process.unlisten(changed)
        end)
        test.it("rejects no-op writes without incrementing the revision", function()
            local initial = invoke("GET", "").body.revision
            local response = invoke("PUT", '{"values":{},"unset":[]}')
            test.eq(response.status, 400)
            test.eq(response.body.kind, errors.INVALID)
            test.is_false(response.body.committed)
            test.eq(invoke("GET", "").body.revision, initial)
        end)
        test.it("returns a native error when the HTTP context is absent", function()
            local _, err = funcs.new():with_context({performance_no_response = true}):call("kickside.settings.api:get_performance")
            test.is_true(errors.is(err, errors.INTERNAL))
            test.eq(err:details().code, "http_context_unavailable")
        end)
    end)
end)}
