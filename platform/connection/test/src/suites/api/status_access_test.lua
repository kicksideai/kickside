local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local contract = require("contract")
local security = require("security")

local function status(actor_id: string, id: string): (any?, error?)
    local actor, actor_err = security.new_actor(actor_id, {})
    test.is_nil(actor_err)
    local scope, scope_err = security.named_scope("wippy.security:process")
    test.is_nil(scope_err)
    local def, def_err = contract.get("kickside.connection:connection")
    test.is_nil(def_err)
    local instance, open_err = def:with_actor(actor):with_scope(scope):open("app:status_access_binding", { component_id = id })
    test.is_nil(open_err)
    return instance:get_status({})
end

local function define_tests()
    test.describe("Connection status access", function()
        local id = uuid.v4()
        local owner = "status-owner-" .. uuid.v4()
        test.before_all(function()
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            db = assert(db)
            local _, insert_err = db:execute([[INSERT INTO kickside_components
                (component_id, impl_id, private_context, created_at, updated_at)
                VALUES ($1, 'app:status_access_binding', '{}', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)]], { id })
            test.is_nil(insert_err)
            local _, grant_err = db:execute([[INSERT INTO kickside_component_access
                (access_id, subject_type, subject_id, component_id, source_component_id, access_mask, created_at)
                VALUES ($1, 'user', $2, $3, $4, 1, CURRENT_TIMESTAMP)]], { uuid.v4(), owner, id, id })
            test.is_nil(grant_err)
            db:release()
        end)
        test.after_all(function()
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            db = assert(db)
            local _, grant_err = db:execute("DELETE FROM kickside_component_access WHERE component_id=$1", { id })
            test.is_nil(grant_err)
            local _, delete_err = db:execute("DELETE FROM kickside_components WHERE component_id=$1", { id })
            test.is_nil(delete_err)
            db:release()
        end)
        test.it("admits a reader opening the raw connection binding", function()
            local result, err = status(owner, id)
            test.is_nil(err)
            test.is_true(result.success)
        end)
        test.it("refuses an unrelated actor supplying another connection ID", function()
            local result, err = status("status-outsider-" .. uuid.v4(), id)
            test.is_nil(result)
            test.is_true(errors.is(err, errors.NOT_FOUND))
        end)
    end)
end
return { run = test.run_cases(define_tests) }
