local test = require("test")
local uuid = require("uuid")
local security = require("security")
local contract = require("contract")
local funcs = require("funcs")

return {run = test.run_cases(function()
    test.describe("connection mutation responses", function()
        test.it("renames a connection and forwards its asynchronous deletion handle", function()
            local actor = security.new_actor("connection-owner-" .. uuid.v4(), {})
            local scope = assert(security.named_scope("wippy.security:process"))
            local service = assert(assert(contract.get("kickside.component:component_service"))
                :with_actor(actor):with_scope(scope):open())
            local registered, register_err = service:register({impl_id = "app:status_access_binding", meta = {title = "Original"}})
            test.is_nil(register_err, tostring(register_err))
            test.is_true(registered.success, tostring(registered.error))
            local exec = funcs.new():with_actor(actor):with_scope(scope)
            local renamed, rename_err = exec:call("kickside.connection.registry:update", {component_id = registered.component_id, name = "Renamed"})
            test.is_nil(rename_err, tostring(rename_err))
            test.eq(renamed.component_id, registered.component_id)
            test.is_nil(renamed.deleted)
            test.eq(service:get({component_id = registered.component_id}).meta.title, "Renamed")
            local accepted, delete_err = exec:call("kickside.connection.registry:delete", {component_id = registered.component_id})
            test.is_nil(delete_err, tostring(delete_err))
            test.eq(accepted.component_id, registered.component_id)
            test.is_false(accepted.deleted)
            test.is_true(accepted.in_progress)
            test.eq(type(accepted.job_id), "string")
            local visible = service:get({component_id = registered.component_id})
            test.not_nil(visible.deleting_at)
            test.eq(visible.deletion_job_id, accepted.job_id)
        end)
    end)
end)}
