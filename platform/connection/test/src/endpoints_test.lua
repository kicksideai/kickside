local test = require("test")
local endpoints = require("endpoints")
local function define_tests()
    test.describe("Declared endpoints", function()
        test.it("reads deployment values and retains enterprise base paths", function()
            test.eq(endpoints.get("app:endpoints", "api"), "https://enterprise.example.invalid/api/v3")
            test.eq(endpoints.get("app:endpoints", "socket"), "wss://gateway.example.invalid/?v=10&encoding=json")
        end)
        test.it("reports missing descriptors, missing keys and invalid URLs", function()
            local ok = pcall(function() endpoints.get("app:absent", "api") end)
            test.is_false(ok)
            local ok = pcall(function() endpoints.get("app:endpoints", "absent") end)
            test.is_false(ok)
            local ok = pcall(function() endpoints.get("app:endpoints", "invalid") end)
            test.is_false(ok)
            local ok = pcall(function() endpoints.get("app:endpoints", "credentials") end)
            test.is_false(ok)
        end)
    end)
end
local cases = test.run_cases(define_tests)
return { run = function(options) return cases(options) end }
