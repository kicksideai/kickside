local test = require("test")
local sql = require("sql")
local uuid = require("uuid")
local funcs = require("funcs")
local security = require("security")
local time = require("time")

return { run = test.run_cases(function()
    test.describe("connection-owned capacity floor", function()
        local ids = {}
        local user = "capacity-" .. uuid.v7()
        local exec = funcs.new():with_actor(security.new_actor(user, {}))
            :with_scope(security.named_scope("wippy.security:process"))

        local function create(): string
            local result, err = exec:call("kickside.connection.registry:register", {
                provider = "jira", name = "capacity " .. uuid.v7(), auth = { token = "original" },
            })
            test.is_nil(err)
            test.not_nil(result)
            ids[#ids + 1] = result.component_id
            return result.component_id
        end
        local function call(id, operation, now, fields): (any, any)
            local args = { component_id = id, operation = operation, now_ms = now }
            for key, value in pairs(fields or {}) do args[key] = value end
            return exec:call("app:capacity_probe", args)
        end
        local function calls(id): integer
            local db = assert(sql.get("app:db"))
            local rows, err = db:query("SELECT COUNT(*) AS n FROM connection_capacity_calls WHERE connection_id=$1", { id })
            db:release()
            test.is_nil(err)
            return tonumber(rows[1].n) :: integer
        end
        test.before_all(function()
            local db = assert(sql.get("app:db"))
            local _, err = db:execute("CREATE TABLE connection_capacity_calls (connection_id TEXT NOT NULL, method TEXT NOT NULL)")
            db:release()
            test.is_nil(err)
        end)
        test.after_all(function()
            local db, err = sql.get("app:db")
            test.is_nil(err)
            db = assert(db)
            for _, id in ipairs(ids) do
                for _, table_name in ipairs({ "kickside_component_access", "kickside_component_meta", "kickside_components" }) do
                    local _, delete_err = db:execute("DELETE FROM " .. table_name .. " WHERE component_id=$1", { id })
                    test.is_nil(delete_err)
                end
            end
            local _, drop_err = db:execute("DROP TABLE connection_capacity_calls")
            test.is_nil(drop_err)
            db:release()
        end)


        test.it("keeps provider rejections as Results and holds later HTTP consumers with typed capacity", function()
            local shared, independent = create(), create()
            local result, err = call(shared, "http", 10000, {limited = true, retry_after_ms = 2000})
            test.is_nil(err)
            test.eq(result.error, "paced")
            test.eq(result.status_code, 429)
            test.is_nil(result.kind)
            test.eq(result.retry_after_ms, 2000)
            local held, held_err = call(shared, "http", 11999)
            test.is_nil(held)
            test.eq(held_err:kind(), errors.RATE_LIMITED)
            test.eq(held_err:details().retry_at_ms, 12000)
            test.eq(calls(shared), 1)
            local free, free_err = call(independent, "http", 11999)
            test.is_nil(free_err)
            test.is_true(free.success)
            test.eq(calls(independent), 1)
            local resumed, resumed_err = call(shared, "http", 12000)
            test.is_nil(resumed_err)
            test.is_true(resumed.success)
            test.eq(calls(shared), 2)
        end)

        test.it("gates transports whose connection identity comes from a capability selector", function()
            local id = create()
            local due = time.now():unix_nano() // 1000000 + 60000
            local _, record_err = call(id, "record", 10000, {retry_at_ms = due})
            test.is_nil(record_err)
            local result, err = call(id, "http_selector", 10000)
            test.is_nil(result)
            test.eq(err:kind(), errors.RATE_LIMITED)
            test.eq(err:details().retry_at_ms, due)
            test.eq(calls(id), 0)
        end)

        test.it("shares capacity signaled by a provider rate-limit classification without rewriting its status", function()
            local id = create()
            local result, err = call(id, "http", 10000, {limited = true, retry_after_ms = 2000, status_code = 403, error_kind = "rate_limited"})
            test.is_nil(err)
            test.eq(result.status_code, 403)
            test.is_nil(result.kind)
            test.eq(result.error_kind, "rate_limited")
            local held, held_err = call(id, "http", 11999)
            test.is_nil(held)
            test.eq(held_err:kind(), errors.RATE_LIMITED)
            test.eq(held_err:details().retry_at_ms, 12000)
            test.eq(calls(id), 1)
        end)

        test.it("holds at-most-once writes before reservation and preserves the exact waiting floor", function()
            local id = create()
            local now = time.now():unix_nano() // 1000000
            local floor = now + 90000
            local _, record_err = call(id, "record", now, { retry_at_ms = floor })
            test.is_nil(record_err)
            local result, err = call(id, "round_sink", now)
            test.is_nil(err)
            test.eq(result.state, "waiting")
            test.eq(result.error.retry_at_ms, floor)
            test.eq(calls(id), 0)
            local db = assert(sql.get("app:db"))
            local rows, read_err = db:query("SELECT COUNT(*) AS n FROM kickside_trigger_item_ledger WHERE owner_id=$1", { id })
            db:release()
            test.is_nil(read_err)
            test.eq(tonumber(rows[1].n), 0)
        end)

        test.it("holds a second consumer on the same connection and leaves another connection available", function()
            local shared, independent = create(), create()
            local absent, absent_err = call(shared, "floor", 10000)
            test.is_nil(absent_err)
            test.is_nil(absent)
            local floor, record_err = call(shared, "record", 10000, { retry_after_ms = 2000 })
            test.is_nil(record_err)
            test.eq(floor, 12000)
            local allowed, wait_err = call(shared, "check", 10000)
            test.is_nil(allowed)
            test.eq(wait_err:kind(), errors.RATE_LIMITED)
            test.eq(wait_err:details().code, "connection_capacity_wait")
            test.eq(wait_err:details().scope, "capacity")
            test.eq(wait_err:details().retry_at_ms, 12000)
            test.eq(wait_err:details().retry_after_ms, 2000)
            local free, free_err = call(independent, "check", 10000)
            test.is_nil(free_err)
            test.is_true(free)
        end)

        test.it("retains the monotonic floor across owner reconstruction and credential replacement", function()
            local id = create()
            local first, first_err = call(id, "record", 10000, { retry_at_ms = 18000 })
            test.is_nil(first_err)
            test.eq(first, 18000)
            local earlier, earlier_err = call(id, "record", 11000, { retry_at_ms = 15000 })
            test.is_nil(earlier_err)
            test.eq(earlier, 18000)
            local changed, change_err = call(id, "credentials", 11000)
            test.is_nil(change_err)
            test.not_nil(changed)
            local recovered, recover_err = call(id, "floor", 11000)
            test.is_nil(recover_err)
            test.eq(recovered, 18000)
            local later, later_err = call(id, "record", 11000, { retry_after_ms = 9000 })
            test.is_nil(later_err)
            test.eq(later, 20000)
        end)

        test.it("resumes at the exact floor without resetting it on expiry", function()
            local id = create()
            local _, record_err = call(id, "record", 10000, { retry_at_ms = 12000 })
            test.is_nil(record_err)
            local before, before_err = call(id, "check", 11999)
            test.is_nil(before)
            test.eq(before_err:details().retry_after_ms, 1)
            local exact, exact_err = call(id, "check", 12000)
            test.is_nil(exact_err)
            test.is_true(exact)
            local after, after_err = call(id, "check", 12001)
            test.is_nil(after_err)
            test.is_true(after)
            local retained, retained_err = call(id, "floor", 12001)
            test.is_nil(retained_err)
            test.eq(retained, 12000)
        end)

        test.it("treats an absolute floor as authoritative across nested consumers", function()
            local id = create()
            local first, first_err = call(id, "record", 10000, {retry_at_ms = 12000, retry_after_ms = 2000})
            test.is_nil(first_err)
            test.eq(first, 12000)
            local nested, nested_err = call(id, "record", 10100, {retry_at_ms = 12000, retry_after_ms = 2000})
            test.is_nil(nested_err)
            test.eq(nested, 12000)
        end)

        test.it("records only typed capacity errors and rejects a missing capacity deadline", function()
            local id = create()
            for _, fields in ipairs({ { kind = errors.UNAVAILABLE, retry_after_ms = 1000 },
                { scope = "item", retry_after_ms = 1000 } }) do
                local result, err = call(id, "record", 10000, fields)
                test.is_nil(err)
                test.is_nil(result)
            end
            local absent, absent_err = call(id, "floor", 10000)
            test.is_nil(absent_err)
            test.is_nil(absent)
            local result, err = call(id, "record", 10000)
            test.is_nil(result)
            test.eq(err:kind(), errors.INVALID)
            test.eq(err:details().code, "connection_capacity_deadline_required")
        end)

        test.it("keeps ordinary metadata edits from lowering the owner floor", function()
            local id = create()
            local changed, err = call(id, "metadata", 10000, { value = 0 })
            test.is_nil(changed)
            test.eq(err:kind(), errors.INVALID)
            test.eq(err:details().code, "component_meta_owner_required")
        end)

        test.it("honors one floor at collection, reconciliation and writable boundaries", function()
            local id = create()
            local now = time.now():unix_nano() // 1000000
            local due = now + 60000
            local _, record_err = call(id, "record", now, { retry_at_ms = due })
            test.is_nil(record_err)
            for _, operation in ipairs({ "source", "keys", "sink" }) do
                local result, err = call(id, operation, now)
                test.is_nil(err)
                test.is_false(result.success)
                test.eq(result.error.kind, errors.RATE_LIMITED)
                test.eq(result.error.code, "connection_capacity_wait")
                test.eq(result.error.retry_at_ms, due)
            end
            test.eq(calls(id), 0, "held consumers invoke no provider")
        end)

        test.it("records capacity from one source before a second consumer invokes that connection", function()
            local shared, independent = create(), create()
            local now = time.now():unix_nano() // 1000000
            local due = now + 60000
            local failed, fail_err = call(shared, "source", now, { limited = true, retry_at_ms = due })
            test.is_nil(fail_err)
            test.is_false(failed.success)
            local floor, floor_err = call(shared, "floor", now)
            test.is_nil(floor_err)
            test.eq(floor, due)
            local held, held_err = call(shared, "sink", now)
            test.is_nil(held_err)
            test.is_false(held.success)
            test.eq(held.error.retry_at_ms, due)
            test.eq(calls(shared), 1)
            local available, available_err = call(independent, "source", now)
            test.is_nil(available_err)
            test.is_true(available.success)
            test.eq(calls(independent), 1)
        end)
    end)
end) }
