local test = require("test")
local base = require("base")
local funcs = require("funcs")
local channel = require("channel")
local time = require("time")
local function define()
    test.describe("connection worker planning", function()
        test.it("plans token changes, additions and removals without mutating workers", function()
            local workers = {keep = {pid = "p1", token = "one"}, rotate = {pid = "p2", token = "old"}, remove = {pid = "p3", token = "three"}}
            local plan = base.plan_workers(workers, {{id = "keep", token = "one"}, {id = "rotate", token = "new"}, {id = "add", token = "four"}})
            test.eq(#plan.start, 1)
            test.eq(plan.start[1].id, "add")
            test.eq(#plan.restart, 1)
            test.eq(plan.restart[1].id, "rotate")
            test.eq(plan.restart[1].token, "new")
            test.eq(#plan.stop, 1)
            test.eq(plan.stop[1], "remove")
            test.eq(workers.rotate.token, "old")
            test.not_nil(workers.remove)
        end)
        test.it("normalizes credentials and removes workers with revoked credentials", function()
            local plan = base.plan_workers({active = {pid = "p", token = " token "}, revoked = {pid = "r", token = "old"}},
                {{id = " active ", token = "token"}, {id = "revoked", token = " "}, {id = "", token = "x"}})
            test.eq(#plan.start, 0)
            test.eq(#plan.restart, 0)
            test.eq(#plan.stop, 1)
            test.eq(plan.stop[1], "revoked")
        end)
        test.it("delivers a configured lifecycle wake through the native projection entry", function()
            local name = "app.connection.worker.wake.test"
            local registered, reg_err = process.registry.register(name, nil, process.registry.CONSISTENT)
            test.is_nil(reg_err, tostring(reg_err))
            test.is_true(registered)
            local body = {worker_config = {hub_name = name}, retained = true}
            local result, err = funcs.call("kickside.connection:reconcile_workers", {projection = {body = body}, range = {to_seq = 7}})
            local _, unregister_err = process.registry.unregister(name, process.registry.CONSISTENT)
            test.is_nil(unregister_err, tostring(unregister_err))
            test.is_nil(err, tostring(err))
            test.eq(result.last_seq, 7)
            test.is_true(result.body.retained)
            local inbox, timeout = process.inbox(), time.after("2s")
            local selected = channel.select({inbox:case_receive(), timeout:case_receive()})
            test.eq(selected.channel, inbox, "projection advances without delivering its wake")
            test.eq(selected.value:topic(), "reconcile")
        end)
        test.it("keeps the lifecycle cursor retryable while its configured hub is absent", function()
            local result, err = funcs.call("kickside.connection:reconcile_workers", {projection = {body = {worker_config = {hub_name = "app.connection.worker.absent"}}}, range = {to_seq = 9}})
            test.is_nil(result)
            test.not_nil(err)
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.is_true(err:retryable())
        end)
    end)
end
return {run = test.run_cases(define)}
