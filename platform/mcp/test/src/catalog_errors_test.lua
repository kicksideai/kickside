local test = require("test")
local presets = require("presets_fixture")
local presets_endpoint = require("presets_endpoint")
local http_state = require("http_state")
local traits = require("traits_fixture")
local surface = require("surface_fixture")
local meta_tools = require("meta_fixture")
local repo = require("repo")
local sql = require("sql")
local json = require("json")
local uuid = require("uuid")

local function define_tests()
    test.describe("MCP catalog errors", function()
        test.it("returns a typed invalid call_tool request", function()
            local result, err = meta_tools.handle("call_tool", {}, {}, nil)
            test.is_nil(result)
            test.is_true(errors.is(err, errors.INVALID), tostring(err))
        end)
        test.it("classifies inactive tools and missing invokers", function()
            local original = surface.build
            surface.build = function() return {}, { active = "test:active" }, nil end
            local inactive, inactive_err = meta_tools.handle("call_tool", { id = "inactive" }, {}, nil)
            local missing, missing_err = meta_tools.handle("call_tool", { id = "active" }, {}, nil)
            local source = errors.new({ kind = errors.UNAVAILABLE, message = "invocation unavailable", details = { retained = true } })
            local failed, failed_err = meta_tools.handle("call_tool", { id = "active" }, {}, function() return nil, source end)
            surface.build = original
            test.is_nil(inactive)
            test.is_true(errors.is(inactive_err, errors.PERMISSION_DENIED), tostring(inactive_err))
            test.is_nil(missing)
            test.is_true(errors.is(missing_err, errors.INTERNAL), tostring(missing_err))
            test.is_nil(failed)
            test.eq(failed_err, source)
        end)
        test.it("propagates registry errors from preset discovery", function()
            local result, err = presets.list()
            test.is_nil(result)
            test.eq(err, "catalog unavailable")
        end)
        test.it("preserves catalog failure at the shared preset expansion boundary", function()
            local policy, err = presets.apply({ preset = "test:preset" })
            test.is_nil(policy)
            test.eq(err, "catalog unavailable")
        end)
        test.it("returns preset discovery failure through the HTTP endpoint", function()
            http_state.reset({})
            presets_endpoint.handler()
            test.eq(http_state.result().status, 500)
            test.is_false(http_state.result().payload.success)
            test.eq(http_state.result().payload.error, "preset discovery failed: catalog unavailable")
            test.is_nil(http_state.result().payload.presets)
        end)
        test.it("returns registry errors from trait discovery and lookup", function()
            local result, err = traits.list_all()
            test.is_nil(result)
            test.eq(err, "catalog unavailable")
            result, err = traits.get("test:trait")
            test.is_nil(result)
            test.eq(err, "catalog unavailable")
            result, err = traits.resolve_tool_ids({ "test:trait" })
            test.is_nil(result)
            test.eq(err, "catalog unavailable")
        end)
        test.it("returns namespace expansion errors", function()
            local result, err = traits.expand_tool_ids({ "test:*" })
            test.is_nil(result)
            test.eq(err, "tool namespace unavailable")
        end)
        test.it("does not return a partial or empty surface on registry failure", function()
            local descriptors, names, err = surface.build({ active_trait_ids = {},
                allowed_tool_ids = { ["test:tool"] = true } })
            test.is_nil(descriptors)
            test.is_nil(names)
            test.eq(err, "catalog unavailable")
            local descriptor, descriptor_err = surface.descriptor_for("test:tool")
            test.is_nil(descriptor)
            test.eq(descriptor_err, "catalog unavailable")
        end)
        test.it("rejects invalid declared schemas on direct and discovered surfaces", function()
            for _, id in ipairs({ "test:broken_schema", "test:scalar_schema", "test:array_schema" }) do
                local descriptors, names, err = surface.build({ active_trait_ids = {}, allowed_tool_ids = { [id] = true } })
                test.is_nil(descriptors)
                test.is_nil(names)
                test.contains(tostring(err), "invalid input_schema")
                local descriptor, descriptor_err = surface.descriptor_for(id)
                test.is_nil(descriptor)
                test.contains(tostring(descriptor_err), "invalid input_schema")
            end
        end)
        test.it("refuses colliding tool aliases rather than returning an incomplete surface", function()
            local descriptors, names, err = surface.build({ active_trait_ids = {},
                allowed_tool_ids = { ["test:collision_a"] = true, ["test:collision_b"] = true } })
            test.is_nil(descriptors)
            test.is_nil(names)
            test.not_nil(err)
            test.eq(err:kind(), errors.CONFLICT)
            test.eq(err:details().code, "TOOL_NAME_COLLISION")
            test.eq(err:details().name, "shared_alias")
        end)

        test.it("refuses real tools that collide with a declared meta-tool name", function()
            local descriptors, names, err = surface.build({ active_trait_ids = {},
                allowed_tool_ids = { ["test:reserved_alias"] = true } })
            test.is_nil(descriptors)
            test.is_nil(names)
            test.eq(err:kind(), errors.CONFLICT)
            test.eq(err:details().code, "TOOL_NAME_COLLISION")
            test.eq(err:details().name, "session_info")
        end)

        test.it("propagates discovery failures through meta-tool error returns", function()
            local result, err = meta_tools.handle("list_traits", {}, {}, nil)
            test.is_nil(result)
            test.eq(err, "catalog unavailable")
        end)
        test.it("keeps the principal unchanged when the credential cannot persist", function()
            local principal = { credential_id = uuid.v7(), active_trait_ids = { "existing:trait" } }
            local result, err = meta_tools.handle("set_traits", { ids = {} }, principal, nil)
            test.is_nil(result)
            test.eq(err, "credential not found")
            test.eq(principal.active_trait_ids[1], "existing:trait")
        end)
        test.it("preserves other context keys and refuses corrupt stored context", function()
            local db = assert(sql.get("app:db"))
            local id = uuid.v7()
            local _, seed_err = db:execute([[INSERT INTO kickside_mcp_credentials
                (credential_id,token_hash,token_prefix,actor_id,context_json,created_at,updated_at)
                VALUES ($1,$1,'test','test',$2,0,0)]], { id, '{"other":"preserved"}' })
            test.is_nil(seed_err, tostring(seed_err))
            local stored, err = repo.persist_active_traits(id, { "test:trait" })
            test.is_true(stored)
            test.is_nil(err, tostring(err))
            local rows, read_err = db:query("SELECT context_json FROM kickside_mcp_credentials WHERE credential_id=$1", { id })
            test.is_nil(read_err, tostring(read_err))
            local ctx = assert(json.decode(rows[1].context_json))
            test.eq(ctx.other, "preserved")
            test.eq(ctx.active_trait_ids[1], "test:trait")
            local _, corrupt_err = db:execute("UPDATE kickside_mcp_credentials SET context_json=$1 WHERE credential_id=$2", { "{broken", id })
            test.is_nil(corrupt_err, tostring(corrupt_err))
            stored, err = repo.persist_active_traits(id, {})
            test.is_false(stored)
            test.is_true(tostring(err):find("credential context is invalid", 1, true) ~= nil)
            rows, read_err = db:query("SELECT context_json FROM kickside_mcp_credentials WHERE credential_id=$1", { id })
            test.is_nil(read_err, tostring(read_err))
            test.eq(rows[1].context_json, "{broken")
            local _, cleanup_err = db:execute("DELETE FROM kickside_mcp_credentials WHERE credential_id=$1", { id })
            test.is_nil(cleanup_err, tostring(cleanup_err))
            db:release()
        end)
    end)
end
return { run = test.run_cases(define_tests) }
