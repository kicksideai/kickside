local test = require("test")
local handler = require("handler_fixture")
local state = require("transport_state")
local function define_tests()
    test.describe("MCP connection transport", function()
        test.it("rejects foreign and opaque origins before reading or dispatching", function()
            for _, origin in ipairs({ "https://evil.example", "null" }) do
                for _, method in ipairs({ "POST", "GET", "DELETE" }) do
                    state.reset("valid", "body must not be read", origin, method)
                    local _, err = handler.handler()
                    test.is_nil(err)
                    test.eq(state.result().status, 403)
                    test.not_nil(state.result().payload.error)
                    test.is_nil(state.result().payload.session_id)
                    test.eq(state.result().body_reads, 0)
                end
            end
        end)
        test.it("refuses unsupported methods before reading the body", function()
            for _, method in ipairs({ "GET", "DELETE" }) do
                state.reset("valid", "body must not be read", nil, method)
                local _, err = handler.handler()
                test.is_nil(err)
                test.eq(state.result().status, 405)
                test.eq(state.result().headers["Allow"], "POST")
                test.eq(state.result().body_reads, 0)
                test.is_nil(state.result().headers["Mcp-Session-Id"])
            end
        end)
        test.it("propagates method errors before reading the body", function()
            state.reset("valid", "body must not be read", nil, "POST", "method read failed")
            local result, err = handler.handler()
            test.is_nil(result)
            test.eq(err, "method read failed")
            test.eq(state.result().body_reads, 0)
        end)
        test.it("admits the configured origin", function()
            state.reset("valid", nil, "https://fixture.invalid")
            local _, err = handler.handler()
            test.is_nil(err)
            test.eq(state.result().status, 200)
        end)
        test.it("echoes a visible session token and forwards it to dispatch", function()
            state.reset("client-connection", nil)
            local _, err = handler.handler()
            test.is_nil(err)
            local result = state.result()
            test.eq(result.headers["Mcp-Session-Id"], "client-connection")
            test.eq(result.payload.session_id, "client-connection")
        end)
        test.it("mints distinct tokens for missing and malformed headers", function()
            local previous = ""
            for _, header in ipairs({ false, "", "white space", "\n", string.rep("x", 129) }) do
                state.reset(header, nil)
                local _, err = handler.handler()
                test.is_nil(err)
                local result = state.result()
                local current = result.headers["Mcp-Session-Id"]
                test.not_nil(current)
                test.is_true(current ~= header)
                test.is_true(current ~= previous)
                test.eq(result.payload.session_id, current)
                previous = current
            end
        end)
        test.it("returns request read errors before dispatch", function()
            state.reset("valid", "request read failed")
            local result, err = handler.handler()
            test.is_nil(result)
            test.eq(err, "request read failed")
            test.is_nil(state.result().payload)
        end)
    end)
end
return { run = test.run_cases(define_tests) }
