local test = require("test")
local security = require("security")
return { run = test.run_cases(function()
    test.describe("Upload deletion host permissions", function()
        test.it("resolves the declared upload test group for durable identity recovery", function()
            local scope, err = security.named_scope("app:uploads_test")
            test.is_nil(err)
            test.not_nil(scope)
        end)
        test.it("allows the declared workspace deletion stage without granting unrelated provider functions", function()
            local actor = security.new_actor("upload-policy-member", { security_groups = { "app.security:user" } })
            local scope = security.named_scope("app.security:user")
            test.eq(scope:evaluate(actor, "funcs.call", "chestor.workspace:file_reap_stage", {}), "allow")
            test.eq(scope:evaluate(actor, "funcs.call", "chestor.workspace:unrelated", {}), "undefined")
        end)
    end)
end) }
