local test = require("test")
local adapter = require("adapter")
local cloud = require("cloud")
local fs_fake = require("fs_fake")
local fs = require("fs")
local uuid = require("uuid")
local function temporary_count(volume)
    local count = 0
    for entry in assert(volume:readdir(".")) do
        if entry.name:sub(1, 13) == ".upload-read-" then count = count + 1 end
    end
    return count
end
return {run = test.run_cases(function()
    test.describe("packed cloud storage", function()
        test.it("stats, streams, reads and deletes through the packed authority", function()
            local storage = assert(adapter.get("app:uploads", "app:db", "app:other_uploads"))
            local path = "s3://app:objects/" .. uuid.v4()
            local bytes = "remote original\nsecond line\n"
            assert(storage:writefile(path, bytes))
            test.eq(#bytes, assert(storage:stat(path)).size)
            test.is_true(storage:exists(path))
            local volume = assert(fs.get("app:uploads"))
            local before = temporary_count(volume)
            local reader = assert(storage:open(path, "r"))
            test.eq(before + 1, temporary_count(volume))
            test.eq(bytes:sub(1, 6), assert(reader:read(6)))
            assert(reader:close())
            test.eq(before, temporary_count(volume))
            test.eq(bytes, assert(storage:readfile(path)))
            test.eq(before, temporary_count(volume))
            assert(storage:remove(path))
            test.is_false(storage:exists(path))
        end)
        test.it("preserves native resource and download errors and removes temporary bytes", function()
            local storage = assert(adapter.get("app:uploads"))
            local _, denied = storage:readfile("s3://app:denied/key")
            test.eq(cloud.denied, denied)
            local path = "s3://app:objects/" .. uuid.v4()
            assert(storage:writefile(path, "bytes"))
            local volume = assert(fs.get("app:uploads"))
            local before = temporary_count(volume)
            cloud.fail_download(true)
            local value, err = storage:readfile(path)
            cloud.fail_download(false)
            assert(storage:remove(path))
            test.is_nil(value)
            test.eq(cloud.failed, err)
            test.eq(before, temporary_count(volume))
        end)
        test.it("retains the native download error when removing temporary bytes also fails", function()
            local storage = assert(adapter.get("app:uploads"))
            local path = "s3://app:objects/" .. uuid.v4()
            assert(storage:writefile(path, "bytes"))
            cloud.fail_download(true)
            fs_fake.fail_cleanup(true)
            local value, err = storage:readfile(path)
            fs_fake.fail_cleanup(false)
            cloud.fail_download(false)
            assert(fs.get("app:uploads")):remove(fs_fake.failed_path)
            assert(storage:remove(path))
            test.is_nil(value)
            test.eq(cloud.failed, err)
        end)
        test.it("rejects malformed packed paths before opening a resource", function()
            local storage = assert(adapter.get("app:uploads"))
            for _, path in ipairs({"s3:///key", "fs://app:uploads/", "s3://app:objects", "ftp://app:objects/key"}) do
                local _, err = storage:stat(path)
                test.is_true(errors.is(err, errors.INVALID), path)
            end
        end)
    end)
end)}
