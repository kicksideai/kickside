local test = require("test")
local uuid = require("uuid")
local security = require("security")
local funcs = require("funcs")
local provision = require("provision")
local records = require("records")
local types = require("types")
local sql = require("sql")
local json = require("json")
local fs = require("fs")
local artifacts_repo = require("artifacts")

local function run_as(id, target, upload_id, args)
    local actor = security.new_actor(id, { security_groups = { "app:uploads_test" } })
    local scope = security.named_scope("wippy.security:process")
    return funcs.new():with_actor(actor):with_scope(scope):with_context({ upload_id = upload_id }):call(target, args or {})
end

return { run = test.run_cases(function()
    test.describe("Shared upload access", function()
        test.it("READ grants expose the owner's upload and revocation removes access", function()
            local owner, reader, stranger = uuid.v4(), uuid.v4(), uuid.v4()
            local db = assert(sql.get("app:db"))
            local _, user_err = db:execute([[INSERT INTO app_users
                (user_id,email,full_name,password_hash,status)
                VALUES ($1,$2,$1,'test-only','active')]], { owner, owner .. "@uploads.test" })
            test.is_nil(user_err, tostring(user_err))
            for _, group_id in ipairs({ "app:uploads_test", "wippy.security:process" }) do
                local _, group_err = db:execute([[INSERT INTO app_user_groups (user_id,group_id)
                    VALUES ($1,$2)]], { owner, group_id })
                test.is_nil(group_err, tostring(group_err))
            end
            db:release()
            local actor = security.new_actor(owner, { security_groups = { "app:uploads_test" } })
            local _, provision_err = provision.ensure_user(actor, security.named_scope("wippy.security:process"), owner)
            test.is_nil(provision_err, tostring(provision_err))
            local component_id = types.component_id_for_owner(owner)
            local id = uuid.v4()
            local storage = assert(fs.get("app:uploads"))
            local _, stored_err = storage:writefile(id, "bytes")
            test.is_nil(stored_err, tostring(stored_err))
            local frozen, frozen_err = run_as(owner, "app:upload_identity_probe", id)
            test.is_nil(frozen_err, tostring(frozen_err))
            local _, create_err = records.create(id, owner, 5, "text/plain", "app:uploads", id, "kickside.uploads:types.generic", { _execution_identity = frozen }, "completed")
            test.is_nil(create_err, tostring(create_err))
            local owned, owner_err = run_as(owner, "app:upload_read_probe", id)
            test.is_nil(owner_err, tostring(owner_err))
            test.eq(owned.status, 200)
            test.eq("/api/v1/uploads/" .. id .. "/raw", owned.body.upload.raw_url)
            local grant, grant_err = run_as(owner, "kickside.component.binding:grant_subtree_func", id, {
                root_component_id = component_id, subject = { subject_id = reader, subject_type = "user" }, access_mask = 1 })
            test.is_nil(grant_err, tostring(grant_err))
            test.is_true(grant.success, grant.error)
            local shared, shared_err = run_as(reader, "app:upload_read_probe", id)
            test.is_nil(shared_err, tostring(shared_err))
            test.eq(shared.status, 200)
            test.eq(shared.body.component_id, component_id)
            test.eq(shared.body.upload.uuid, id)
            local artifacts, artifacts_err = run_as(reader, "app:upload_artifacts_probe", id)
            test.is_nil(artifacts_err, tostring(artifacts_err))
            test.eq(artifacts.status, 200)
            local raw, raw_err = run_as(reader, "app:upload_raw_probe", id)
            test.is_nil(raw_err, tostring(raw_err))
            test.eq(raw.status, 200)
            test.eq(raw.body, "bytes")
            local remote_path = "s3://app:objects/" .. id .. ".pdf"
            local remote_db = assert(sql.get("app:db"))
            assert(remote_db:execute("UPDATE kickside_uploads SET storage_path=$1 WHERE uuid=$2", {remote_path, id}))
            remote_db:release()
            local artifact = assert(artifacts_repo.create_artifact({upload_id = id, kind = "image", role = "part",
                mime_type = "image/png", label = "page.png", locator = {type = "storage", storage_id = "app:uploads", storage_path = "s3://app:objects/page.png"}}))
            local source = assert(artifacts_repo.create_artifact({upload_id = id, kind = "document", role = "part",
                mime_type = "application/pdf", label = "source.pdf", locator = {type = "upload.original", storage_id = "app:uploads", storage_path = id}}))
            local blob = assert(artifacts_repo.create_artifact({upload_id = id, kind = "image", role = "part",
                mime_type = "image/png", label = "blob.png", content = "image bytes"}))
            local stored_blob = assert(artifacts_repo.get_blob(blob.blob_id))
            local blob_db = assert(sql.get("app:db"))
            assert(blob_db:execute("UPDATE kickside_upload_artifact_blobs SET storage_path=$1 WHERE blob_id=$2",
                {"s3://app:objects/blob.png", blob.blob_id}))
            blob_db:release()
            for _, who in ipairs({owner, reader}) do
                local remote = assert(run_as(who, "app:upload_read_probe", id))
                test.eq(200, remote.status)
                test.eq("https://objects.example/" .. id .. ".pdf?expiration=900", remote.body.upload.raw_url)
                local remote_artifacts = assert(run_as(who, "app:upload_artifacts_probe", id))
                test.eq(200, remote_artifacts.status)
                local urls = {}
                for _, item in ipairs(remote_artifacts.body.artifacts) do urls[item.artifact_id] = item.raw_url end
                test.eq("https://objects.example/page.png?expiration=900", urls[artifact.artifact_id])
                test.eq("https://objects.example/" .. id .. ".pdf?expiration=900", urls[source.artifact_id])
                test.eq("https://objects.example/blob.png?expiration=900", urls[blob.artifact_id])
            end
            local listed = assert(run_as(owner, "app:signed_upload_list_probe", id))
            test.eq(200, listed.status)
            test.eq("https://objects.example/" .. id .. ".pdf?expiration=900", listed.body.uploads[1].raw_url)
            local private = assert(run_as(stranger, "app:upload_read_probe", id))
            test.is_true(private.status == 403 or private.status == 404)
            test.is_nil(private.body.upload)
            local private_list = assert(run_as(stranger, "app:signed_upload_list_probe", id))
            test.eq(200, private_list.status)
            test.eq(0, #private_list.body.uploads)
            local private_artifacts = assert(run_as(stranger, "app:upload_artifacts_probe", id))
            test.is_true(private_artifacts.status == 403 or private_artifacts.status == 404)
            test.is_nil(private_artifacts.body.artifacts)
            local restored = assert(sql.get("app:db"))
            assert(restored:execute("UPDATE kickside_uploads SET storage_path=$1 WHERE uuid=$2", {id, id}))
            restored:release()
            assert(storage:remove(stored_blob.storage_path))
            local cleanup = assert(sql.get("app:db"))
            assert(cleanup:execute("DELETE FROM kickside_upload_artifacts WHERE upload_id=$1", {id}))
            assert(cleanup:execute("DELETE FROM kickside_upload_artifact_blobs WHERE blob_id=$1", {blob.blob_id}))
            cleanup:release()
            local direct, direct_err = run_as(reader, "kickside.uploads:delete_owned", id, { upload_id = id })
            test.is_nil(direct)
            test.not_nil(direct_err)
            local no_delete, no_delete_err = run_as(reader, "app:upload_delete_probe", id)
            test.is_nil(no_delete_err, tostring(no_delete_err))
            test.eq(no_delete.status, 403)
            local hidden, hidden_err = run_as(stranger, "app:upload_read_probe", id)
            test.is_nil(hidden_err, tostring(hidden_err))
            test.is_true(hidden.status == 403 or hidden.status == 404)
            test.is_nil(hidden.body.upload)
            local revoked, revoke_err = run_as(owner, "kickside.component.binding:revoke_subtree_func", id, {
                root_component_id = component_id, subject = { subject_id = reader, subject_type = "user" } })
            test.is_nil(revoke_err, tostring(revoke_err))
            test.is_true(revoked.success, revoked.error)
            local denied, denial_err = run_as(reader, "app:upload_read_probe", id)
            test.is_nil(denial_err, tostring(denial_err))
            test.is_true(denied.status == 403 or denied.status == 404)
            test.is_nil(denied.body.upload)
            local delete_grant, delete_grant_err = run_as(owner, "kickside.component.binding:grant_subtree_func", id, {
                root_component_id = component_id, subject = { subject_id = reader, subject_type = "user" }, access_mask = 4 })
            test.is_nil(delete_grant_err, tostring(delete_grant_err))
            test.is_true(delete_grant.success, delete_grant.error)
            local deleted, delete_err = run_as(reader, "app:upload_delete_probe", id)
            test.is_nil(delete_err, tostring(delete_err))
            test.eq(deleted.status, 200, json.encode(deleted.body))
            local owner_events, events_err = run_as(owner, "app:upload_events_probe", id)
            test.is_nil(events_err, tostring(events_err))
            local found = false
            for _, event in ipairs(owner_events.events or {}) do
                if event.type == types.EVENT.DELETED and json.decode(event.body).upload_id == id then found = true end
            end
            test.is_true(found, "shared deletion is missing from the owner's durable upload events: " .. json.encode(owner_events))
            local absent = run_as(owner, "app:upload_read_probe", id)
            test.eq(absent.status, 404)
        end)
    end)
end) }
