local test = require("test")
local security = require("security")
local funcs = require("funcs")
local function call(kind, policy)
    local scope = assert(security.new_scope({assert(security.policy("app:native_storage_call_probe")), assert(security.policy(policy))}))
    return funcs.new():with_actor(assert(security.new_actor("storage-reader", {}))):with_scope(scope)
        :call("app:native_storage_error_probe", {kind = kind})
end
return {run = test.run_cases(function()
    test.describe("native storage error seams", function()
        test.it("returns a missing cloud resource through data and error", function()
            local result, err = call("s3", "app:native_storage_allow_missing")
            test.is_nil(err, tostring(err))
            test.is_true(result.returned)
            test.is_true(result.missing)
            test.is_true(result.not_found, result.message)
        end)
        test.it("returns denied filesystem access through data and error", function()
            local result, err = call("fs", "app:native_storage_deny")
            test.is_nil(err, tostring(err))
            test.is_true(result.returned)
            test.is_true(result.missing)
            test.is_true(result.denied, result.message)
        end)
        test.it("returns denied cloud access through data and error", function()
            local result, err = call("s3", "app:native_storage_deny")
            test.is_nil(err, tostring(err))
            test.is_true(result.returned)
            test.is_true(result.missing)
            test.is_true(result.denied, result.message)
        end)
    end)
end)}
