-- Fixed ciphertext emitted by the previous implementation with the synthetic ab key.
-- The completion fixture uses a fixed issuance clock so it remains valid.
local test = require("test")
local env = require("env")
local caller = require("caller")
local crypto = require("crypto")
local base64 = require("base64")
local json = require("json")

return {run = test.run_cases(function()
    test.describe("stored ciphertext compatibility", function()
        test.it("reads ciphertext from the previous implementation through the environment key", function()
            local previous, env_err = env.get("ENCRYPTION_KEY")
            test.is_nil(env_err)
            local _, set_err = env.set("ENCRYPTION_KEY", string.rep("ab", 32))
            test.is_nil(set_err)
            local value, err = caller.unpack("mxC4R2MuYroEBelwotgAJxaDGkUF3SzAmbh+OO9MF2pPkipTyx1v/fuCGrGonpFu4I13g0kXlalm1TG43uv872gI+Sra8rwoZL+SbdUhOH6LLSNMtgl7yXS7ymyprbHaLv/rgZfhmjhOdghTkgiZ3TIfFJlC0KOrMgp5fJuOC8/vZwFRgm6cqj08WCfJ65s+1tsy+rAVAiIN0Zy14TM19A==")
            local packed, pack_err = caller.pack({upload_id="upload-fixture", function_id="example:complete",
                actor_id="fixture-actor", actor_context={}})
            local decoded, decode_err = base64.decode(packed)
            local plain, decrypt_err = crypto.decrypt.aes(decoded, string.rep(string.char(171), 32))
            local payload, json_err = json.decode(plain)
            local _, restore_err = env.set("ENCRYPTION_KEY", previous)
            test.is_nil(restore_err)
            test.is_nil(err)
            test.eq(value.upload_id, "upload-fixture")
            test.eq(value.actor_id, "fixture-actor")
            test.eq(value.function_id, "example:complete")
            test.eq(value.issued_at, 4102444800)
            test.is_nil(pack_err)
            test.is_nil(decode_err)
            test.is_nil(decrypt_err)
            test.is_nil(json_err)
            test.eq(payload.upload_id, "upload-fixture")
            test.eq(payload.actor_id, "fixture-actor")
        end)
    end)
end)}
