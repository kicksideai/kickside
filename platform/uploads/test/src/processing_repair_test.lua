local test = require("test")
local sql = require("sql")
local repo = require("upload_query_repo")
local process_job = require("process_job")
local funcs = require("funcs")

return test.run_cases(function()
    test.describe("bounded processing repair", function()
        test.it("upgrades earlier upload rows and preserves an existing repair checkpoint", function()
            local id = "app:processing_repair_migration_db"
            local db = assert(sql.get(id))
            if tostring(db:type()) == sql.type.POSTGRES then
                assert(db:execute("CREATE SCHEMA IF NOT EXISTS uploads_repair_upgrade"))
            end
            assert(db:execute("CREATE TABLE kickside_uploads(uuid TEXT PRIMARY KEY,storage_state TEXT,processing_job_id TEXT)"))
            assert(db:execute("INSERT INTO kickside_uploads VALUES ('earlier-upload','uploaded','earlier-job')"))
            local function apply(name)
                local result, err = funcs.call("kickside.uploads.migrations:06_processing_repair_cursor",
                    {database_id = id, id = name, direction = "up"})
                test.is_nil(err, tostring(err))
                test.eq(result.failed, 0)
            end
            apply("processing-repair-upgrade")
            test.eq(assert(db:query("SELECT after_id FROM kickside_upload_processing_repair WHERE id=1"))[1].after_id, "")
            assert(db:execute("UPDATE kickside_upload_processing_repair SET after_id='earlier-upload' WHERE id=1"))
            apply("processing-repair-reapply")
            test.eq(assert(db:query("SELECT after_id FROM kickside_upload_processing_repair WHERE id=1"))[1].after_id, "earlier-upload")
            local row = assert(db:query("SELECT * FROM kickside_uploads"))[1]
            test.eq(row.uuid, "earlier-upload")
            test.eq(row.storage_state, "uploaded")
            test.eq(row.processing_job_id, "earlier-job")
            db:release()
        end)

        test.it("advances a durable candidate cursor across sparse matches and wraps", function()
            local db = assert(sql.get("app:db"))
            assert(db:execute([[WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i+1 FROM n WHERE i<100000)
                INSERT INTO kickside_uploads(uuid,actor_id,size,mime_type,storage_state,storage_id,storage_path,metadata,
                    processing_intent_state,processing_job_id)
                SELECT 'window-' || CAST(100000+i AS TEXT),'window-owner',1,'text/plain','uploaded','app:uploads','fixture','{}',
                    CASE WHEN i=99999 THEN 'acknowledged' ELSE NULL END,NULL FROM n]]))
            assert(db:execute("UPDATE kickside_upload_processing_repair SET after_id='window-100000' WHERE id=1"))
            local candidates, err, progress = repo.list_dead_processing_jobs(500)
            test.is_nil(err, tostring(err))
            test.not_nil(progress, "candidate inspection returns its durable progress independently of matches")
            test.eq(progress.inspected, 500)
            test.is_true(progress.needs_continue)
            test.eq(#candidates, 0, "a match beyond the candidate window is not inspected")
            local repaired, repair_err, more = process_job.repair_dead(500)
            test.is_nil(repair_err)
            test.eq(repaired, 0)
            test.is_true(more, "the maintenance continuation follows inspected candidates, not matches")
            -- A fresh repository call resumes after the persisted window.
            local _, next_err, next_progress = repo.list_dead_processing_jobs(500)
            test.is_nil(next_err)
            test.is_true(next_progress.after_id > progress.after_id)
            test.is_nil(repo.advance_processing_repair_cursor(next_progress))
            test.is_nil(repo.advance_processing_repair_cursor(progress))
            test.eq(assert(db:query("SELECT after_id FROM kickside_upload_processing_repair WHERE id=1"))[1].after_id,
                next_progress.after_id, "an older pass cannot overwrite a later checkpoint")
            -- Position just before the sparse match, as a resumed installation does.
            assert(db:execute("UPDATE kickside_upload_processing_repair SET after_id='window-199998' WHERE id=1"))
            local found, found_err, tail = repo.list_dead_processing_jobs(500)
            test.is_nil(found_err)
            test.eq(tail.inspected, 2)
            test.is_false(tail.needs_continue)
            test.eq(#found, 1)
            test.eq(found[1].upload_id, "window-199999")
            test.is_nil(repo.advance_processing_repair_cursor(tail))
            local checkpoint = assert(db:query("SELECT after_id FROM kickside_upload_processing_repair WHERE id=1"))
            test.eq(checkpoint[1].after_id, "")
            assert(db:execute("DELETE FROM kickside_uploads WHERE actor_id='window-owner'"))
            db:release()
        end)
    end)
end)
