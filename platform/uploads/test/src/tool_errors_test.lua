local test = require("test")
local funcs = require("funcs")
local security = require("security")
local registry = require("registry")
local json = require("json")

local function define_tests()
    test.describe("canonical tool failures", function()
        test.it("ViewFiles declares only implemented inputs", function()
            local entry = assert(registry.get("kickside.uploads.traits:view_files"))
            local schema = assert(json.decode(entry.meta.input_schema))
            test.is_nil(schema.properties.format)
        end)
        test.it("ViewFiles returns an error when every requested file fails", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:view_files", { upload_ids = { "missing-upload" } })
            test.is_nil(result)
            test.is_true(errors.is(err, errors.INTERNAL))
            test.is_true(tostring(err) ~= "")
        end)
        test.it("kickside.uploads.traits:count_files rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:count_files", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.PERMISSION_DENIED), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("Authentication required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.uploads.traits:list_files rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:list_files", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.PERMISSION_DENIED), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("Authentication required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.uploads.traits:view_files rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:view_files", {  })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.PERMISSION_DENIED), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("Authentication required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.uploads.traits:fetch_url rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:fetch_url", { url = "" })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.INVALID), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("url is required", 1, true) ~= nil, tostring(err))
        end)
        test.it("kickside.uploads.traits:upload_file rejects failures through the error return", function()
            local exec = funcs.new():with_actor(security.new_actor("tool_error_contract", {}))
                :with_scope(security.named_scope("kickside.uploads.tool_errors:tool_errors_scope"))
            local result, err = exec:call("kickside.uploads.traits:upload_file", { filename = "" })
            test.is_nil(result, "a failing tool must not return a successful result")
            test.not_nil(err, "a failing tool must return an invocation error")
            test.is_true(errors.is(err, errors.INVALID), "error kind: " .. tostring(err))
            test.is_true(tostring(err):find("filename is required", 1, true) ~= nil, tostring(err))
        end)
    end)
end

return { run = test.run_cases(define_tests) }
