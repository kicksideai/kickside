local function execute(statement, args)
    local db = assert(sql.get("app:db"))
    local result, err = db:execute(statement, args)
    db:release()
    assert(not err, tostring(err))
    return result
end

local function query(statement, args)
    local db = assert(sql.get("app:db"))
    local result, err = db:query(statement, args)
    db:release()
    assert(not err, tostring(err))
    return result
end

local function fixture(bot, creator, group_ids)
    local id = assert(crypto.random.uuid())
    test.not_nil((users.create_passwordless({user_id = id, email = id .. "@bots.invalid", full_name = "Original", status = "active"})))
    owned[#owned + 1] = id
    for _, group_id in ipairs(group_ids or {"app.security:admin"}) do
        test.not_nil((groups.assign_user_to_group(id, group_id)))
    end
    if bot then
        execute("INSERT INTO app_user_bot_accounts (user_id, created_by, created_at) VALUES ($1, $2, $3)",
            {id, creator or "deleted-creator", "2026-10-09T00:00:00Z"})
    end
    return id
end

local function audit(id)
    return query("SELECT audit_id, actor_id, user_id, operation, payload, created_at FROM app_user_bot_audit WHERE user_id = $1 ORDER BY created_at, audit_id", {id})
end

local function next_audit(id, previous)
    local records = audit(id)
    test.eq(#records, 2)
    local added
    for _, row in ipairs(records) do
        if row.audit_id == previous.audit_id then
            test.eq(row.payload, previous.payload)
            test.eq(row.actor_id, previous.actor_id)
        else added = row end
    end
    test.not_nil(added)
    return added
end

local function retained(id)
    local user = assert(users.get(id))
    test.eq(user.status, "inactive")
    test.eq(user.email, id .. "@bots.invalid")
    test.eq(#query("SELECT user_id FROM app_user_bot_accounts WHERE user_id = $1", {id}), 1)
    test.eq(#query("SELECT group_id FROM app_user_groups WHERE user_id = $1", {id}), 1)
    return user
end

