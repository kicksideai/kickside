local test = require("test")
local directory = require("directory")
local funcs = require("funcs")
local security = require("security")
local user_repo = require("user_repo")
local user_groups_repo = require("user_groups_repo")
local crypto = require("crypto")

local function define_tests()
    test.describe("host MCP group resolution", function()
        test.it("resolves the caller through the owned reader without exposing subject lookup", function()
            local suffix = assert(crypto.random.uuid())
            local user = assert(user_repo.create({email = suffix .. "@test.local",
                password = "Northwind-2026!", full_name = "Resolver Caller", status = "active"}))
            local other = assert(user_repo.create({email = "other-" .. suffix .. "@test.local",
                password = "Northwind-2026!", full_name = "Other Resolver Subject", status = "active"}))
            local _, group_err = user_groups_repo.assign_user_to_group(user.user_id, "app.security:scope_sales")
            test.is_nil(group_err)
            local scope = assert(security.new_scope({assert(security.policy("app:mcp_resolver_caller"))}))
            local actor = security.new_actor(user.user_id)
            local authority = assert(security.named_scope("app.security:scope_sales"))
            test.eq(authority:evaluate(actor, "kickside.execution.delegate", "*"), "undefined")
            test.eq(scope:evaluate(actor, "funcs.call", "kickside.users.binding:subject_lookup"), "undefined")
            local executor = assert(funcs.new()):with_actor(actor):with_scope(scope)
            local result, result_err = executor:call("app:resolver_caller_probe", {
                subject_id = user.user_id, other_id = other.user_id})
            test.is_nil(result_err)
            test.is_nil(result.resolve_error)
            test.eq(result.resolved.principal.id, user.user_id)
            test.eq(result.resolved.actor_id, user.user_id)
            test.eq(result.resolved.groups[1], "app.security:scope_sales")
            test.is_nil(result.denied)
            test.is_true(result.denial_permission)
            test.is_nil(result.direct)
            test.is_true(result.direct_permission)
            test.eq(result.reader_before, "undefined")
            test.eq(result.reader_after, "undefined")
            test.eq(result.actor_after, user.user_id)
        end)
        test.it("expands group members under Users ownership for a caller without database authority", function()
            local suffix, suffix_err = crypto.random.uuid()
            test.is_nil(suffix_err)
            local user, create_err = user_repo.create({ email = suffix .. "@test.local",
                password = "Northwind-2026!", full_name = "Realtime Member", status = "active" })
            test.is_nil(create_err)
            local group = "realtime-" .. suffix
            local _, assign_err = user_groups_repo.assign_user_to_group(user.user_id, group)
            test.is_nil(assign_err)
            local policy, policy_err = security.policy("app:group_members_caller")
            test.is_nil(policy_err)
            local executor, executor_err = funcs.new()
            test.is_nil(executor_err)
            local bound = executor:with_actor(security.new_actor(user.user_id))
                :with_scope(security.new_scope({ policy }))
            local members, members_err = bound:call("kickside.users.binding:group_members_func", { group_id = group })
            test.is_nil(members_err)
            test.is_nil(members.error)
            test.eq(#members.user_ids, 1)
            test.eq(members.user_ids[1], user.user_id)
            local _, remove_err = user_groups_repo.remove_user_from_group(user.user_id, group)
            test.is_nil(remove_err)
            local removed, removed_err = bound:call("kickside.users.binding:group_members_func", { group_id = group })
            test.is_nil(removed_err)
            test.is_nil(removed.error)
            test.eq(#removed.user_ids, 0)
        end)

        test.it("propagates failure of the shared subject reader through directory membership", function()
            local suffix, suffix_err = crypto.random.uuid()
            test.is_nil(suffix_err)
            local user, create_err = user_repo.create({ email = suffix .. "@test.local",
                password = "Northwind-2026!", full_name = "Directory Subject", status = "active" })
            test.is_nil(create_err)
            local called_target, called_subject = nil, nil
            local previous = rawget(directory, "_funcs")
            rawset(directory, "_funcs", { new = function()
                return { call = function(_, target, args)
                    called_target, called_subject = target, args.subject_id
                    return nil, errors.new({ kind = errors.UNAVAILABLE, message = "subject reader unavailable", retryable = true })
                end }
            end })
            local answer, err = directory.groups({ id = user.user_id })
            rawset(directory, "_funcs", previous)
            test.is_nil(answer)
            test.is_true(errors.is(err, errors.UNAVAILABLE), tostring(err))
            test.eq(called_target, "kickside.users.binding:subject_lookup")
            test.eq(called_subject, user.user_id)
            local padded, padded_err = directory.groups({ id = " " .. user.user_id .. " " })
            test.is_nil(padded_err)
            test.is_false(padded.active)
            test.eq(#padded.groups, 0)
        end)

        test.it("reads live groups under the Users identity for a caller without store authority", function()
            local suffix, suffix_err = crypto.random.uuid()
            test.is_nil(suffix_err)
            local user, create_err = user_repo.create({ email = suffix .. "@test.local",
                password = "Northwind-2026!", full_name = "MCP Member", status = "active" })
            test.is_nil(create_err)
            local _, group_err = user_groups_repo.assign_user_to_group(user.user_id, "app.security:user")
            test.is_nil(group_err)
            local policy, policy_err = security.policy("app:mcp_resolver_caller")
            test.is_nil(policy_err)
            local executor, executor_err = funcs.new()
            test.is_nil(executor_err)
            local bound = executor:with_actor(security.new_actor(user.user_id))
                :with_scope(security.new_scope({ policy }))
            local first, first_err = bound:call("kickside.users.directory:directory_groups", { id = user.user_id })
            test.is_nil(first_err)
            test.is_true(first.active)
            test.eq(#first.groups, 1)
            test.eq(first.groups[1], "app.security:user")
            local _, add_err = user_groups_repo.assign_user_to_group(user.user_id, "app.security:admin")
            test.is_nil(add_err)
            local second, second_err = bound:call("kickside.users.directory:directory_groups", { id = user.user_id })
            test.is_nil(second_err)
            test.eq(#second.groups, 2)
            local seen = {}
            for _, group in ipairs(second.groups) do seen[group] = true end
            test.is_true(seen["app.security:admin"])
            test.is_true(seen["app.security:user"])
        end)
    end)
end
return { run = test.run_cases(define_tests) }
