local test = require("test")
local sql = require("sql")
local crypto = require("crypto")
local security = require("security")
local registry = require("registry")
local execution_identity = require("execution_identity")
local trigger_reconcile = require("trigger_reconcile")
local session = require("session")
local user_repo = require("user_repo")
local user_groups_repo = require("user_groups_repo")
local user_lifecycle_repo = require("user_lifecycle_repo")
local session_index = require("session_index")
local subject_lookup = require("subject_lookup")

return { run = test.run_cases(function()
    test.describe("delegated authority lifecycle", function()
        local uid
        local password = "delegation-password-2026"
        local function current() local value, err = user_groups_repo.get_user_with_groups(uid); test.is_nil(err, tostring(err)); return assert(value) end
        local function generation() return current().delegation_generation end
        test.before_each(function()
            uid = "delegation-" .. assert(crypto.random.uuid())
            test.not_nil((user_repo.create({user_id = uid, email = uid .. "@test.local", password = password, status = "active"})))
            test.not_nil((user_groups_repo.assign_user_to_group(uid, "app.security:user")))
        end)
        test.after_each(function() local value, err = user_lifecycle_repo.delete(uid); test.is_nil(err, tostring(err)); test.not_nil(value) end)
        test.it("keeps expansions and logout-all while reductions remain revoked after restoration", function()
            test.eq(generation(), 0)
            test.not_nil((user_groups_repo.assign_user_to_group(uid, "app.security:admin")))
            test.eq(generation(), 0)
            test.not_nil((session_index.invalidate_user(uid)))
            test.eq(generation(), 0)
            test.not_nil((user_groups_repo.remove_user_from_group(uid, "app.security:admin")))
            test.eq(generation(), 1)
            test.not_nil((user_groups_repo.assign_user_to_group(uid, "app.security:admin")))
            test.eq(generation(), 1)
            local looked = subject_lookup.lookup({subject_id = uid})
            test.eq(looked.authority_epochs["kickside.users:" .. uid], 1)
            test.eq(looked.initial_authority_epochs["kickside.users:" .. uid], 0)
        end)
        test.it("retains every live group in authority-only subject lookups", function()
            local original = assert(registry.current_version())
            local changes = assert(registry.snapshot()):changes()
            changes:create({id = "app:authority_only_admin_deny", kind = "security.policy", data = {
                groups = {"app.security:admin"}, policy = {
                    actions = "access", resources = "app:authority_only_admin_marker", effect = "deny"}}})
            assert(changes:apply())
            assert(trigger_reconcile.trigger())
            local ok, failure = pcall(function()
                test.not_nil((user_groups_repo.assign_user_to_group(uid, "app.security:admin")))
                local looked = subject_lookup.lookup({subject_id = uid, authority_only = true})
                test.is_nil(looked.error)
                local found = {}
                for _, group in ipairs(looked.groups) do found[group] = true end
                test.is_true(found["app.security:user"] == true)
                test.is_true(found["app.security:admin"] == true)
                local authority_epoch = looked.authority_epochs["kickside.users:" .. uid]
                local actor = assert(security.new_actor("user:" .. uid))
                local scope = assert(execution_identity.scope_from_groups(looked.scope_groups, looked.scope_policy_ids))
                test.eq(scope:evaluate(actor, "access", "app:authority_only_admin_marker"), "deny")
                test.not_nil((user_groups_repo.remove_user_from_group(uid, "app.security:admin")))
                local reduced = subject_lookup.lookup({subject_id = uid, authority_only = true})
                test.is_nil(reduced.error)
                local remaining = {}
                for _, group in ipairs(reduced.groups) do remaining[group] = true end
                test.is_true(remaining["app.security:user"] == true)
                test.is_nil(remaining["app.security:admin"])
                local reduced_scope = assert(execution_identity.scope_from_groups(reduced.scope_groups, reduced.scope_policy_ids))
                test.eq(reduced_scope:evaluate(actor, "access", "app:authority_only_admin_marker"), "allow")
                test.eq(reduced.authority_epochs["kickside.users:" .. uid], authority_epoch + 1)
            end)
            test.is_true(assert(registry.apply_version(original)))
            if not ok then error(failure) end
        end)
        test.it("advances on status and password mutations", function()
            test.not_nil((user_lifecycle_repo.update(uid, {status = "inactive"})))
            test.eq(generation(), 1)
            test.not_nil((user_lifecycle_repo.update(uid, {status = "active"})))
            test.eq(generation(), 2)
            test.not_nil((user_lifecycle_repo.update(uid, {password = password .. "-new"})))
            test.eq(generation(), 3)
        end)
        test.it("retains deletion epochs when an id is reused", function()
            test.not_nil((user_lifecycle_repo.delete(uid)))
            test.not_nil((user_repo.create({user_id = uid, email = uid .. "@test.local", password = password, status = "active"})))
            test.eq(generation(), 1)
        end)
        test.it("rolls delegated invalidation back with its account transaction", function()
            local db = assert(sql.get("app:db"))
            local tx = assert(db:begin())
            local changed, change_err = session_index.invalidate_user_in(tx, uid, {revoke_delegations = true})
            test.is_nil(change_err); test.not_nil(changed)
            test.is_nil(select(2, tx:rollback()))
            db:release()
            test.eq(generation(), 0)
        end)
        test.it("derives session epochs and reserves them against provider metadata", function()
            local minted, mint_err = session.mint(current(), {authority_epochs = {forged = 999}})
            test.is_nil(mint_err)
            test.not_nil(minted)
            local meta = assert(minted.actor):meta()
            test.eq(meta.authority_epochs["kickside.users:" .. uid], 0)
            test.is_nil(meta.authority_epochs.forged)
        end)
    end)
end) }
