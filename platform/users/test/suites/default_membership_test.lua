local test = require("test")
local users = require("user_repo")
local groups = require("user_groups_repo")
local sources = require("user_group_sources_repo")
local contract = require("contract")
local defaults = require("default_groups")
local consts = require("user_consts")
local lifecycle = require("user_lifecycle_repo")
local registry = require("registry")

return test.run_cases(function()
    test.describe("declarative default memberships", function()
        test.it("applies application new-account defaults alongside a provisioning caller's default group", function()
            local snapshot, snapshot_err = registry.snapshot()
            test.is_nil(snapshot_err)
            local changes = snapshot:changes()
            changes:create({id = "app:new_account_default", kind = "registry.entry",
                meta = {type = "kickside.users.default_membership"},
                data = {group_id = "test:declared_members", new_users = true}})
            local _, apply_err = changes:apply()
            test.is_nil(apply_err)
            local result, resolve_err = defaults.resolve("test:provider_default")
            local cleanup = assert(registry.snapshot()):changes()
            cleanup:delete("app:new_account_default")
            local _, cleanup_err = cleanup:apply()
            test.is_nil(cleanup_err)
            test.is_nil(resolve_err)
            local groups = {}
            for _, id in ipairs(result) do groups[id] = true end
            test.eq(groups["test:provider_default"], true)
            test.eq(groups["test:declared_members"], true)
        end)
        test.it("uses the app setting for new accounts", function()
            local definition, definition_err = contract.get("kickside.settings:settings")
            test.is_nil(definition_err)
            test.not_nil(definition)
            local settings, open_err = definition:open()
            test.is_nil(open_err)
            local configured = consts.get_config().default_group_id
            local initial, initial_err = defaults.resolve(configured)
            test.is_nil(initial_err)
            test.eq(initial[1], configured)
            local saved = settings:set({namespace = "kickside.users", key = "join_default_group", value = false})
            test.eq(saved.success, true)
            local narrowed, narrowed_err = defaults.resolve(configured)
            test.is_nil(narrowed_err)
            test.eq(#narrowed, 0)
            local cleared = settings:unset({namespace = "kickside.users", key = "join_default_group"})
            test.eq(cleared.success, true)
            local restored, restored_err = defaults.resolve(configured)
            test.is_nil(restored_err)
            test.eq(restored[1], configured)
        end)
        test.it("enrolls existing accounts once and preserves an administrator's removal", function()
            local uid = "default_membership_user"
            local created, create_err = users.create({ user_id = uid, email = uid .. "@test.local",
                password = "testpass123", status = "active" })
            test.is_nil(create_err)
            test.not_nil(created)
            local assigned, assign_err = groups.assign_user_to_group(uid, "app.security:user")
            test.is_nil(assign_err)
            test.not_nil(assigned)
            local initialized, initialize_err = sources.initialize_default_group("test:members", "test:membership_defaults")
            test.is_nil(initialize_err)
            test.not_nil(initialized)
            test.eq(initialized.initialized, true)
            local membership, read_err = groups.get_user_groups(uid)
            test.is_nil(read_err)
            local found = {}
            for _, id in ipairs(membership.groups) do found[id] = true end
            test.eq(found["app.security:user"], true)
            test.eq(found["test:members"], true)
            local removed, remove_err = groups.remove_user_from_group(uid, "test:members")
            test.is_nil(remove_err)
            test.eq(removed.removed, true)
            local replay, replay_err = sources.initialize_default_group("test:members", "test:membership_defaults")
            test.is_nil(replay_err)
            test.eq(replay.initialized, false)
            test.eq(replay.groups_added, 0)
            membership, read_err = groups.get_user_groups(uid)
            test.is_nil(read_err)
            test.eq(#membership.groups, 1)
            test.eq(membership.groups[1], "app.security:user")
            local deleted, delete_err = lifecycle.delete(uid)
            test.is_nil(delete_err)
            test.not_nil(deleted)
        end)
    end)
end)
