local test = require("test")
local funcs = require("funcs")
return {run = test.run_cases(function()
    test.describe("delegation fencing errors", function()
        test.it("preserves transaction classification and details through the public function boundary", function()
            local result, err = funcs.call("kickside.users:delegation_fencing_failure_probe", {group_ids = {"app:fencing_group"}})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.RATE_LIMITED))
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "fencing_dependency")
            test.eq(err:details().nested.marker, "kept")
        end)
        test.it("rejects a malformed request with the native validation code", function()
            local result, err = funcs.call("kickside.users.persist:delegation_fencer", false)
            test.is_nil(result); test.is_true(errors.is(err, errors.INVALID))
            test.eq(err:details().code, "MISSING_REQUIRED_FIELD")
        end)
    end)
end)}
