local test = require("test")
local registry = require("registry")
local funcs = require("funcs")
local security = require("security")
local crypto = require("crypto")
local user_repo = require("user_repo")
local user_lifecycle_repo = require("user_lifecycle_repo")
local user_groups_repo = require("user_groups_repo")
local user_group_sources_repo = require("user_group_sources_repo")
local session = require("session")
local scope_store = require("scope_store")
local trigger_reconcile = require("trigger_reconcile")

local function define_tests()
    test.describe("custom session revocation binding", function()
        test.it("retains revocation and uses the declared fencing default without a new host binding", function()
            local config = assert(registry.get("kickside.security:composition_config"))
            test.eq(config.meta.sessions_invalidator, "kickside.users:custom_session_revoker")
            test.eq(config.meta.delegation_fencer, "kickside.users.persist:delegation_fencer")
            local revoker = assert(registry.get(config.meta.sessions_invalidator))
            test.is_nil((revoker.meta or {}).delegation_fencer)
            local suffix = assert(crypto.random.uuid()):gsub("-", "")
            local uid, slug = "binding_user_" .. suffix, "binding_group_" .. suffix
            local group, policy_id = "kickside.security.scopes:" .. slug, "kickside.users:binding_policy_" .. suffix
            local changes = assert(registry.snapshot()):changes()
            changes:create({id = policy_id, kind = "security.policy", data = {
                policy = {actions = "access", resources = "app:binding_before", effect = "allow"}}})
            test.is_nil(select(2, changes:apply()))
            test.not_nil((scope_store.upsert({slug = slug, policies = {policy_id}}, "tester")))
            test.not_nil((trigger_reconcile.trigger()))
            test.not_nil((user_repo.create({user_id = uid, email = uid .. "@test.local",
                password = "testpass123", status = "active"})))
            test.not_nil((user_group_sources_repo.set_user_groups(uid, {group, "app.security:scope_support"})))
            local minted = assert(session.mint(assert(user_groups_repo.get_user_with_groups(uid))))
            local before = assert(user_repo.get(uid)).auth_generation
            local delegation_before = assert(user_groups_repo.get_user_with_groups(uid)).delegation_generation
            local policy = assert(registry.get(policy_id))
            policy.id = policy_id .. "_after"
            policy.data.policy.resources = "app:binding_after"
            changes = assert(registry.snapshot()):changes()
            changes:create(policy)
            test.is_nil(select(2, changes:apply()))
            test.not_nil((scope_store.upsert({slug = slug, policies = {policy_id .. "_after"}}, "tester")))
            local projected, projection_err = trigger_reconcile.trigger()
            test.is_nil(projection_err)
            test.not_nil(projected)
            test.eq(assert(user_repo.get(uid)).auth_generation, before)
            test.is_true(assert(user_groups_repo.get_user_with_groups(uid)).delegation_generation > delegation_before)
            local tokens = assert(security.token_store("kickside.users.security:tokens"))
            local actor, scope, validate_err = tokens:validate(minted.token)
            test.is_nil(validate_err)
            test.eq(actor:id(), uid)
            test.eq(scope:evaluate(actor, "access", "app:binding_before"), "undefined")
            test.eq(scope:evaluate(actor, "access", "app:binding_after"), "allow")
            local revoked, revoke_err = funcs.call(config.meta.sessions_invalidator, {user_id = uid})
            test.is_nil(revoke_err)
            test.is_true(revoked.success)
            test.eq(revoked.revoked, 1)
            test.is_true(assert(user_repo.get(uid)).auth_generation > before)
            test.not_nil(select(3, tokens:validate(minted.token)))
            tokens:close()
            test.not_nil((user_lifecycle_repo.delete(uid)))
            test.is_true((scope_store.delete(slug)))
            test.not_nil((trigger_reconcile.trigger()))
            changes = assert(registry.snapshot()):changes()
            changes:delete(policy_id)
            changes:delete(policy_id .. "_after")
            test.is_nil(select(2, changes:apply()))
        end)
    end)
end

return {run = test.run_cases(define_tests)}
