local function execute(query)
    local db = assert(sql.get("app:db"))
    local result, err = query:run_with(db):exec()
    db:release()
    if err then error(tostring(err)) end
    return result
end

local function fixture(passwordless, marked)
    local id = assert(crypto.random.uuid())
    local create = passwordless and users.create_passwordless or users.create
    local user, err = create({user_id = id, email = id .. "@test.local", password = PASSWORD, status = "active"})
    test.is_nil(err)
    test.not_nil(user)
    fixtures[#fixtures + 1] = id
    test.not_nil((groups.assign_user_to_group(id, "app.security:admin")))
    test.not_nil((groups.assign_user_to_group(id, "app.security:user")))
    if marked then
        execute(sql.builder.insert("app_user_bot_accounts"):set_map({
            user_id = id, created_by = "deleted-creator", created_at = "2026-10-09T00:00:00Z",
        }))
    end
    return id
end

local function login(id)
    local gateway = assert(registry.get("app:gateway"))
    local port = assert(tostring(gateway.data.addr):match(":(%d+)$"))
    local response, err = http_client.post("http://127.0.0.1:" .. port .. "/api/public/user/token", {
        headers = {["Content-Type"] = "application/json"},
        body = json.encode({email = id .. "@test.local", password = PASSWORD}),
    })
    test.is_nil(err)
    return response, assert(json.decode(response.body))
end

local function no_sessions(id)
    local db = assert(sql.get("app:db"))
    local rows, err = sql.builder.select("COUNT(*) AS count"):from("kickside_user_sessions")
        :where("user_id = ?", id):run_with(db):query()
    db:release()
    test.is_nil(err)
    test.eq(tonumber(rows[1].count), 0)
end

